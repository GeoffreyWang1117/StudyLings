# 资源经济学等领域有广泛应用。
#
# -----------------------------------------------------------------------------
# 1. 连续时间最优控制问题
# -----------------------------------------------------------------------------
#
# 标准形式：
#
#   max_{c(t)} ∫₀^∞ e^{-ρt} U(c(t), x(t)) dt
#
#   s.t. ẋ(t) = f(x(t), c(t))
#        x(0) = x₀ (初始条件)
#        lim_{t→∞} e^{-ρt} λ(t) x(t) = 0 (横截条件)
#
# 其中：
#   - c(t): 控制变量（如消费）
#   - x(t): 状态变量（如资本存量）
#   - ρ: 贴现率（时间偏好）
#   - U: 瞬时效用函数
#   - f: 状态转移方程
#
# -----------------------------------------------------------------------------
# 2. 哈密顿函数（Hamiltonian）
# -----------------------------------------------------------------------------
#
# 哈密顿函数是求解最优控制问题的关键工具：
#
#   H(x, c, λ, t) = U(c, x) + λ × f(x, c)
#
# 或现值哈密顿（Current-value Hamiltonian）：
#
#   Ĥ(x, c, λ) = U(c, x) + λ × f(x, c)
#
# 其中 λ 是共态变量（costate variable），也称为影子价格或拉格朗日乘子。
#
# 经济解释：
# -----------
# - H 表示"广义收益"：即期效用 + 状态变化的价值
# - λ 是状态变量的边际价值（多一单位资本的价值）
# - λ × f 是资本积累的价值
#
# -----------------------------------------------------------------------------
# 3. 最优性条件（庞特里亚金最大值原理）
# -----------------------------------------------------------------------------
#
# 庞特里亚金（Pontryagin）最大值原理给出必要条件：
#
# 3.1 控制条件（一阶条件）
# -------------------------
#   ∂H/∂c = 0
#
#   即：∂U/∂c + λ × ∂f/∂c = 0
#
#   经济含义：消费的边际效用 = 资本的边际价值 × 消费对资本的边际影响
#
# 3.2 共态方程（Costate Equation）
# --------------------------------
#   λ̇ = ρλ - ∂H/∂x
#
#   或：λ̇/λ = ρ - ∂H/∂x / λ
#
#   经济含义：影子价格的变化率 = 贴现率 - 资本的边际产出
#   这是资产定价的无套利条件。
#
# 3.3 状态方程
# ------------
#   ẋ = f(x, c) = ∂H/∂λ
#
# 3.4 横截条件（Transversality Condition）
# ----------------------------------------
#   lim_{t→∞} e^{-ρt} λ(t) x(t) = 0
#
#   经济含义：最优路径上，资本的贴现价值趋于零
#   这排除了过度积累或庞氏骗局。
#
# -----------------------------------------------------------------------------
# 4. Ramsey最优增长模型
# -----------------------------------------------------------------------------
#
# Ramsey模型是最重要的新古典增长模型：
#
# 4.1 模型设定
# ------------
# 效用函数（CRRA）：
#   U(c) = c^{1-σ} / (1-σ)    若 σ ≠ 1
#   U(c) = ln(c)              若 σ = 1
#
# 其中 σ 是跨期替代弹性的倒数（也是相对风险厌恶系数）
#
# 生产函数（Cobb-Douglas）：
#   Y = K^α × L^{1-α} = k^α  (人均形式，假设L=1)
#
# 资本积累方程：
#   K̇ = Y - δK - C
#   或 k̇ = k^α - δk - c  (人均形式)
#
# 4.2 哈密顿函数
# --------------
#   H = c^{1-σ}/(1-σ) + λ(k^α - δk - c)
#
# 4.3 最优性条件
# --------------
# 控制条件：
#   ∂H/∂c = 0
#   c^{-σ} = λ
#
# 共态方程：
#   λ̇ = ρλ - ∂H/∂k
#   λ̇ = ρλ - λ(αk^{α-1} - δ)
#   λ̇/λ = ρ - (αk^{α-1} - δ)
#
# 4.4 欧拉方程（Euler Equation）
# ------------------------------
# 将控制条件对时间求导，结合共态方程：
#
#   ċ/c = (1/σ) × (αk^{α-1} - δ - ρ)
#
# 或更一般地：
#   ċ/c = (1/σ) × (r - ρ)
#
# 其中 r = f'(k) - δ 是净资本回报率
#
# 经济含义：
# - 若 r > ρ：资本回报高于时间偏好，消费增长
# - 若 r < ρ：资本回报低于时间偏好，消费下降
# - 若 r = ρ：消费恒定（稳态）
#
# 4.5 稳态分析
# ------------
# 稳态要求 k̇ = 0 且 ċ = 0
#
# 由欧拉方程，ċ = 0 意味着：
#   αk*^{α-1} = ρ + δ
#   k* = (α/(ρ+δ))^{1/(1-α)}
#
# 这就是修正的黄金律（Modified Golden Rule）。
#
# 稳态消费：
#   c* = k*^α - δk*
#
# 4.6 鞍点稳定性（Saddle-Point Stability）
# ----------------------------------------
# Ramsey模型的稳态是一个鞍点：
# - 存在唯一收敛到稳态的路径（稳定流形）
# - 其他路径发散（不满足横截条件）
#
# 相图分析：
# - k̇ = 0 曲线：c = k^α - δk
# - ċ = 0 曲线：k = k*（垂直线）
# - 两条曲线交点是稳态
#
# -----------------------------------------------------------------------------
# 5. 数值求解方法
# -----------------------------------------------------------------------------
#
# 5.1 射击法（Shooting Method）
# -----------------------------
# 思路：猜测初始共态变量或控制变量，向前积分，调整猜测直到满足边界条件
#
# 步骤：
# 1. 给定k₀，猜测c₀
# 2. 根据动态方程积分到时间T
# 3. 检查是否接近稳态(k*, c*)
# 4. 若不收敛，调整c₀并重复
#
# 二分法调整：
# - 若路径发散到上方（c过高），降低c₀
# - 若路径发散到下方（c过低），提高c₀
#
# 5.2 时间消除法（Time Elimination）
# ----------------------------------
# 将时间消除，直接求解c作为k的函数：
#   dc/dk = ċ/k̇
#
# 5.3 动态规划（值函数迭代）
# -------------------------
# 求解HJB方程（Hamilton-Jacobi-Bellman）：
#   ρV(x) = max_c {U(c) + V'(x) × f(x,c)}
#
# -----------------------------------------------------------------------------
# 6. 其他最优控制应用
# -----------------------------------------------------------------------------
#
# 6.1 最优资源开采（Hotelling规则）
# ---------------------------------
#   ṗ/p = r
# 资源价格增长率等于利率。
#
# 6.2 最优货币政策
# ----------------
# 中央银行最小化损失函数：
#   L = ∫ e^{-ρt} [(π-π*)² + λ(y-y*)²] dt
#
# 6.3 人力资本积累
# ----------------
