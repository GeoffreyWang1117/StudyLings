# 理论背景
# =============================================================================
#
# 贝叶斯计量经济学是将贝叶斯统计方法应用于经济学建模和推断的学科。
# 它在宏观经济学（DSGE模型估计）、金融计量（波动率建模）、
# 微观计量（处理效应）等领域有广泛应用。
#
# -----------------------------------------------------------------------------
# 1. 贝叶斯定理（Bayes' Theorem）
# -----------------------------------------------------------------------------
#
# 核心公式：
#
#   p(θ|y) = p(y|θ) × p(θ) / p(y)
#
# 或简写为：
#   后验 ∝ 似然 × 先验
#   Posterior ∝ Likelihood × Prior
#
# 其中：
#   - p(θ|y): 后验分布（观测数据后对参数的信念）
#   - p(y|θ): 似然函数（给定参数时数据的概率）
#   - p(θ): 先验分布（观测数据前对参数的信念）
#   - p(y): 边际似然/证据（归一化常数）
#
# 经济学解释：
# -------------
# 贝叶斯方法允许我们：
# 1. 形式化地结合先验知识（如经济理论、前期研究）
# 2. 获得参数的完整分布，而非点估计
# 3. 进行概率性预测和不确定性量化
#
# -----------------------------------------------------------------------------
# 2. 频率学派 vs 贝叶斯学派
# -----------------------------------------------------------------------------
#
# 频率学派（Frequentist）：
# -------------------------
# - 参数是固定但未知的常数
# - 置信区间："长期来看，95%的区间包含真实参数"
# - 假设检验基于p值
# - 不使用先验信息
#
# 贝叶斯学派（Bayesian）：
# -------------------------
# - 参数是随机变量，具有概率分布
# - 可信区间："参数有95%概率在此区间内"
# - 假设检验基于后验概率或贝叶斯因子
# - 明确使用先验信息
#
# 两种方法的选择：
# -----------------
# - 频率：大样本、客观性要求高
# - 贝叶斯：小样本、有可靠先验、需要完整不确定性
#
# -----------------------------------------------------------------------------
# 3. 共轭先验（Conjugate Prior）
# -----------------------------------------------------------------------------
#
# 定义：若后验分布与先验分布属于同一分布族，则称先验为共轭先验。
#
# 优点：后验分布有解析解，无需数值方法。
#
# 常见共轭对：
# -------------
# 似然              先验                后验
# Normal(μ,σ²已知)  Normal(μ₀,τ₀²)    Normal(μₙ,τₙ²)
# Normal(σ²,μ已知)  Inverse-Gamma      Inverse-Gamma
# Bernoulli(p)      Beta(α,β)          Beta(α+s,β+f)
# Poisson(λ)        Gamma(α,β)         Gamma(α+Σx,β+n)
# Exponential(λ)    Gamma(α,β)         Gamma(α+n,β+Σx)
#
# 3.1 正态-正态共轭
# ------------------
# 模型：y_i ~ N(μ, σ²)，σ²已知
# 先验：μ ~ N(μ₀, τ₀²)
#
# 后验：μ|y ~ N(μₙ, τₙ²)
#
# 其中：
#   精度（precision）定义为方差的倒数
#   τₙ² = 1 / (1/τ₀² + n/σ²)  （后验方差）
#   μₙ = τₙ² × (μ₀/τ₀² + n×ȳ/σ²)  （后验均值）
#
# 或用精度表示：
#   后验精度 = 先验精度 + 数据精度
#   后验均值 = (先验精度×先验均值 + 数据精度×样本均值) / 后验精度
#
# 3.2 贝叶斯线性回归
# -------------------
# 模型：y = Xβ + ε，ε ~ N(0, σ²I)
# 先验：β ~ N(β₀, Σ₀)，σ²已知
#
# 后验：β|y ~ N(βₙ, Σₙ)
#
# 其中：
#   Σₙ = (Σ₀⁻¹ + X'X/σ²)⁻¹
#   βₙ = Σₙ(Σ₀⁻¹β₀ + X'y/σ²)
#
# -----------------------------------------------------------------------------
# 4. MCMC采样方法
# -----------------------------------------------------------------------------
#
# 当后验分布没有解析解时，需要使用马尔可夫链蒙特卡洛（MCMC）方法。
#
# 4.1 Metropolis-Hastings算法
# ----------------------------
# 核心思想：构造马尔可夫链，其平稳分布是目标后验分布。
#
# 算法步骤：
# 1. 初始化 θ⁽⁰⁾
# 2. 对 t = 1, 2, ..., T：
#    a. 从提议分布 q(θ*|θ⁽ᵗ⁻¹⁾) 抽取候选值 θ*
#    b. 计算接受概率：
#       α = min(1, [p(θ*|y) × q(θ⁽ᵗ⁻¹⁾|θ*)] / [p(θ⁽ᵗ⁻¹⁾|y) × q(θ*|θ⁽ᵗ⁻¹⁾)])
#    c. 以概率α接受θ*，否则θ⁽ᵗ⁾ = θ⁽ᵗ⁻¹⁾
#
# 对称提议分布（Random Walk MH）：
#   q(θ*|θ) = q(θ|θ*)
#   则 α = min(1, p(θ*|y) / p(θ⁽ᵗ⁻¹⁾|y))
#
# 调参建议：
# - 接受率目标：20%-50%（单参数约44%，多参数约23%）
# - 提议分布标准差太大：接受率低，链移动慢
# - 提议分布标准差太小：接受率高但探索效率低
#
# 4.2 Gibbs采样（Gibbs Sampler）
# ------------------------------
# 适用于可以分块采样的情况。
#
# 对参数向量 θ = (θ₁, θ₂, ..., θₖ)：
# 1. 初始化 θ⁽⁰⁾ = (θ₁⁽⁰⁾, ..., θₖ⁽⁰⁾)
# 2. 对 t = 1, 2, ..., T：
#    a. θ₁⁽ᵗ⁾ ~ p(θ₁ | θ₂⁽ᵗ⁻¹⁾, ..., θₖ⁽ᵗ⁻¹⁾, y)
#    b. θ₂⁽ᵗ⁾ ~ p(θ₂ | θ₁⁽ᵗ⁾, θ₃⁽ᵗ⁻¹⁾, ..., θₖ⁽ᵗ⁻¹⁾, y)
#    c. ...
#    k. θₖ⁽ᵗ⁾ ~ p(θₖ | θ₁⁽ᵗ⁾, ..., θₖ₋₁⁽ᵗ⁾, y)
#
# 优点：若条件分布是标准分布，可直接采样
# 缺点：参数高度相关时混合慢
#
# 线性回归的Gibbs采样：
# ----------------------
# 交替采样 β 和 σ²：
#   β|σ², y ~ N(βₙ, σ²(X'X)⁻¹)
#   σ²|β, y ~ Inverse-Gamma(n/2, RSS/2)
#
# 其中 RSS = (y - Xβ)'(y - Xβ)
#
# 4.3 MCMC诊断
# -------------
# 需要检查链是否收敛：
#
# - 轨迹图（Trace plot）：参数值随迭代的变化
# - 自相关图：检查样本独立性
# - R-hat统计量：多链收敛诊断（<1.1表示收敛）
# - 有效样本量（ESS）：考虑自相关后的等效独立样本数
#
# -----------------------------------------------------------------------------
# 5. 贝叶斯模型比较
# -----------------------------------------------------------------------------
#
# 5.1 贝叶斯因子（Bayes Factor）
# ------------------------------
# 比较两个模型M₁和M₂：
#
#   BF₁₂ = p(y|M₁) / p(y|M₂)
#
# 其中 p(y|M) = ∫ p(y|θ,M) p(θ|M) dθ 是边际似然。
#
# 解释（Jeffreys准则）：
#   BF > 100: M₁有决定性优势
#   BF > 30: M₁有非常强的优势
#   BF > 10: M₁有强优势
#   BF > 3: M₁有实质优势
#   1 < BF < 3: M₁有轻微优势
#   BF ≈ 1: 两模型相当
#
# 5.2 边际似然计算
# -----------------
# 边际似然通常难以计算，常用方法：
# - 调和均值估计（不稳定）
# - 桥采样（Bridge Sampling）
# - 拉普拉斯近似
# - 变分推断
#
# 5.3 DIC和WAIC
# --------------
# 信息准则的贝叶斯版本：
#   DIC = D̄ + pD  （偏差信息准则）
#   WAIC = -2(lppd - p_eff)  （广泛适用信息准则）
#
# -----------------------------------------------------------------------------
# 6. 后验预测分布
# -----------------------------------------------------------------------------
#
# 预测新观测 y_new：
#
#   p(y_new|y) = ∫ p(y_new|θ) p(θ|y) dθ
#
# 用MCMC样本近似：
#   对每个后验样本 θ⁽ˢ⁾，抽取 y_new⁽ˢ⁾ ~ p(y_new|θ⁽ˢ⁾)
#   预测分布由 {y_new⁽ˢ⁾} 近似
#
# 预测区间：预测分布的分位数区间
#
# -----------------------------------------------------------------------------
# 7. 可信区间（Credible Interval）
# -----------------------------------------------------------------------------
#
# 贝叶斯的区间估计称为可信区间：
#
# 7.1 等尾可信区间（Equal-Tailed）
# --------------------------------
# 包含后验分布中央的(1-α)概率质量：
#   [q_{α/2}, q_{1-α/2}]
# 其中 q_p 是后验分布的p分位数
#
# 7.2 最高后验密度区间（HPD）
# ---------------------------
# 包含后验密度最高的点：
#   {θ : p(θ|y) ≥ c}
# 其中c使区间包含(1-α)概率
#
# HPD区间最短，但可能不连续（多峰分布时）
#
# -----------------------------------------------------------------------------
# 8. 贝叶斯计量经济学应用
# -----------------------------------------------------------------------------
#
# 8.1 DSGE模型估计
# -----------------
# 动态随机一般均衡模型通常用贝叶斯方法估计：
# - 先验：基于校准或前期研究
# - 似然：基于状态空间表示
# - 采样：Metropolis-Hastings或SMC
#
# 8.2 向量自回归（BVAR）
# -----------------------
# 贝叶斯VAR使用先验缩减参数数量：
# - Minnesota先验：自回归参数接近1
# - 可解决过拟合问题
#
# 8.3 随机波动率模型
# -------------------
# 金融时间序列的波动率建模：
#   y_t = σ_t ε_t
#   log(σ_t²) = μ + φ(log(σ_{t-1}²) - μ) + η_t
#
