# 理论背景
# =============================================================================
#
# 基于代理的模型（Agent-Based Model, ABM）是计算经济学的重要分支，
# 它通过模拟大量异质性个体（代理）的交互行为来研究复杂经济系统的涌现现象。
#
# -----------------------------------------------------------------------------
# 1. ABM的核心理念
# -----------------------------------------------------------------------------
#
# 传统经济学模型通常假设：
#   - 代表性代理（所有人相同）
#   - 完全理性（最优决策）
#   - 均衡分析（静态或稳态）
#
# ABM则允许：
#   - 代理异质性：每个代理可有不同的参数、策略、信息
#   - 有限理性：简单规则、学习、适应性行为
#   - 非均衡动态：系统可能永远不收敛到均衡
#   - 涌现现象：宏观规律从微观交互中自然产生
#
# -----------------------------------------------------------------------------
# 2. ABM的基本结构
# -----------------------------------------------------------------------------
#
# 2.1 代理（Agent）
# -----------------
# 每个代理具有：
#   - 状态变量：财富、持仓、信念等
#   - 决策规则：如何根据信息做出选择
#   - 学习机制：如何更新策略或信念
#
# 2.2 环境（Environment）
# -----------------------
# 代理交互的场所：
#   - 市场：价格形成、交易匹配
#   - 网络：社会关系、信息传播
#   - 空间：地理位置、邻近效应
#
# 2.3 模拟循环
# ------------
# 典型的ABM模拟步骤：
#   1. 初始化：创建代理，设置初始状态
#   2. 交互：代理根据规则做出决策并相互作用
#   3. 更新：根据交互结果更新代理状态和环境
#   4. 记录：收集统计数据
#   5. 重复2-4直到达到终止条件
#
# -----------------------------------------------------------------------------
# 3. 经典ABM模型
# -----------------------------------------------------------------------------
#
# 3.1 人工股票市场（Santa Fe模型）
# --------------------------------
# 圣塔菲研究所开发的经典模型：
#   - 代理使用不同的预测规则
#   - 通过遗传算法进化策略
#   - 产生肥尾分布、波动聚集等风格化事实
#
# 3.2 财富交换模型（Yard-Sale模型）
# ---------------------------------
# 研究财富不平等的简单模型：
#   - 每期两个代理随机配对
#   - 进行"公平"赌博
#   - 结果：即使公平游戏也会产生极端不平等
#
# 数学描述：
#   设代理i和j配对，赌注为 ε × min(wᵢ, wⱼ)
#   赢家获得赌注，输家失去赌注
#   结果：财富将集中到少数人手中（财富凝聚）
#
# 3.3 羊群效应模型
# ----------------
# 模拟金融市场中的跟风行为：
#   - 部分代理根据基本面交易
#   - 部分代理模仿他人行为
#   - 可产生泡沫和崩盘
#
# 羊群行为概率：
#   P(跟风) = h × |净买入比例|
#   其中 h 是羊群敏感性参数
#
# -----------------------------------------------------------------------------
# 4. 涌现现象（Emergence）
# -----------------------------------------------------------------------------
#
# ABM能产生许多无法从个体规则直接预测的宏观现象：
#
# 4.1 财富分布的幂律
# ------------------
# 简单交换规则可产生帕累托分布：
#   P(W > w) ∝ w^(-α)
# 这与真实财富分布惊人吻合。
#
# 4.2 市场的风格化事实
# --------------------
#   - 收益率肥尾分布（非正态）
#   - 波动聚集（大波动后跟着大波动）
#   - 长记忆（自相关慢衰减）
#   - 杠杆效应（负收益增加波动）
#
# 4.3 网络效应
# ------------
#   - 相变：系统状态突然改变
#   - 级联失败：局部冲击引发全局崩溃
#   - 临界态：系统在稳定与不稳定边缘
#
# -----------------------------------------------------------------------------
# 5. 基尼系数（Gini Coefficient）
# -----------------------------------------------------------------------------
#
# 衡量不平等程度的重要指标：
#
# 几何定义：
#   G = A / (A + B)
#   其中A是洛伦兹曲线与45度线之间的面积
#
# 计算公式：
#   G = (2 × Σᵢ i × xᵢ) / (n × Σxᵢ) - (n+1)/n
#   其中xᵢ是按升序排列的财富
#
# 或等价地：
#   G = (Σᵢ Σⱼ |xᵢ - xⱼ|) / (2n² × μ)
#
# 解释：
#   - G = 0：完全平等（每人财富相同）
#   - G = 1：完全不平等（一人拥有所有）
#   - 现实中发达国家约0.25-0.40，发展中国家可达0.50以上
#
# -----------------------------------------------------------------------------
# 6. 参数敏感性分析
# -----------------------------------------------------------------------------
#
# ABM结果通常依赖于参数设置，需要系统性分析：
#
# 6.1 单参数分析
# --------------
# 固定其他参数，改变一个参数，观察输出变化
#
# 6.2 蒙特卡洛分析
# ----------------
# 由于ABM通常含有随机性，需要多次运行取统计量：
#   - 均值：期望输出
#   - 标准差：输出波动性
#   - 分位数：极端情况
#
# 6.3 全局敏感性分析
# ------------------
# 同时改变多个参数，分析交互效应：
#   - Sobol指数
#   - Morris方法
#
# -----------------------------------------------------------------------------
# 7. ABM的优缺点
# -----------------------------------------------------------------------------
#
# 优点：
#   - 能捕捉异质性和复杂交互
#   - 产生丰富的动态和涌现现象
#   - 直观，易于扩展
#   - 可作为政策模拟器
#
# 缺点：
#   - 参数校准困难
#   - 结果可能对参数敏感
#   - 缺乏解析解，需要大量计算
#   - 难以进行严格的统计推断
