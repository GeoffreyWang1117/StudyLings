# 说明：
# 本练习将学习需求价格弹性的概念和计算方法。
# 弹性是经济学中衡量"敏感程度"的核心工具。
#
# 【理论背景】
# 价格弹性（Price Elasticity）衡量的是需求量或供给量对价格变化的敏感程度。
# 它回答了一个关键问题：当价格变化1%时，需求量会变化多少？
#
# 【需求价格弹性 (Price Elasticity of Demand, PED/Ed)】
#
# 定义：需求量变化的百分比 除以 价格变化的百分比
#
# 基本公式：
# Ed = (需求量变化百分比) / (价格变化百分比)
#    = (%ΔQ) / (%ΔP)
#    = (ΔQ/Q) / (ΔP/P)
#    = (ΔQ/ΔP) × (P/Q)
#
# 其中：
# - ΔQ = 需求量的变化量 (Q2 - Q1)
# - ΔP = 价格的变化量 (P2 - P1)
# - P, Q = 基准点的价格和数量
#
# 【弹性的符号与绝对值】
# 由于需求定律，价格和需求量反向变动，所以需求价格弹性通常为负数。
# 在经济学分析中，我们通常使用绝对值 |Ed| 来比较弹性大小：
#
# |Ed| > 1：弹性需求 (Elastic Demand)
#   - 需求量对价格变化非常敏感
#   - 价格上涨1%，需求量下降超过1%
#   - 例如：奢侈品、可替代品多的商品
#   - 定价策略：降价可增加总收益
#
# |Ed| = 1：单位弹性 (Unit Elastic)
#   - 需求量变化百分比等于价格变化百分比
#   - 价格变化对总收益没有影响
#
# |Ed| < 1：非弹性需求 (Inelastic Demand)
#   - 需求量对价格变化不敏感
#   - 价格上涨1%，需求量下降小于1%
#   - 例如：必需品、垄断商品、无替代品的商品
#   - 定价策略：涨价可增加总收益
#
# 【两种弹性计算方法】
#
# 1. 点弹性 (Point Elasticity)
#    使用需求曲线上某一点的数据和导数
#    Ed = (dQ/dP) × (P/Q)
#    - 适用于已知需求函数的情况
#    - 例如：需求函数 Q = 100 - 2P，则 dQ/dP = -2
#
# 2. 弧弹性 (Arc Elasticity) / 中点法 (Midpoint Method)
#    使用两点之间的平均价格和平均数量
#    Ed = [(Q2-Q1)/((Q1+Q2)/2)] / [(P2-P1)/((P1+P2)/2)]
#       = [(Q2-Q1)/(Q1+Q2)] / [(P2-P1)/(P1+P2)]
#    - 避免了"基点选择"问题
#    - 从A到B和从B到A计算结果相同
#    - 更适用于实际数据分析
#
# 【弹性与总收益的关系】
# 总收益 TR = P × Q
#
# - 弹性需求 (|Ed| > 1)：降价 → 需求量增加更多 → 总收益增加
# - 非弹性需求 (|Ed| < 1)：降价 → 需求量增加较少 → 总收益减少
# - 单位弹性 (|Ed| = 1)：降价 → 总收益不变
#
