# 本练习是 elasticity1 的延续，将学习另外两种重要的弹性概念：
# 交叉价格弹性和收入弹性。
# 这些弹性帮助我们理解商品之间的关系以及收入变化对需求的影响。
#
# 【理论背景】
# 除了自身价格弹性，经济学家还关注：
# 1. 其他商品的价格如何影响本商品的需求（交叉价格弹性）
# 2. 消费者收入如何影响商品需求（收入弹性）
#
# ============================================
# 【交叉价格弹性 (Cross-Price Elasticity of Demand, XED)】
# ============================================
#
# 定义：商品A需求量变化的百分比 除以 商品B价格变化的百分比
#
# 公式（中点法）：
# XED = (%ΔQa) / (%ΔPb)
#     = [(Qa2-Qa1)/((Qa1+Qa2)/2)] / [(Pb2-Pb1)/((Pb1+Pb2)/2)]
#
# 交叉弹性的符号决定了商品之间的关系：
#
# 1. XED > 0：替代品 (Substitutes)
#    - 商品B价格上升 → 商品A需求增加
#    - 原因：消费者从B转向购买A
#    - 例如：可口可乐与百事可乐、牛肉与猪肉、公交与地铁
#    - XED越大，替代性越强
#
# 2. XED < 0：互补品 (Complements)
#    - 商品B价格上升 → 商品A需求减少
#    - 原因：两种商品通常一起使用
#    - 例如：汽车与汽油、咖啡与糖、打印机与墨盒
#    - |XED|越大，互补性越强
#
# 3. XED ≈ 0：独立品 (Independent Goods)
#    - 商品B价格变化对商品A需求几乎没有影响
#    - 两种商品之间没有明显的经济关联
#    - 例如：铅笔与牛奶、书籍与袜子
#
# ============================================
# 【收入弹性 (Income Elasticity of Demand, YED)】
# ============================================
#
# 定义：需求量变化的百分比 除以 收入变化的百分比
#
# 公式（中点法）：
# YED = (%ΔQ) / (%ΔI)
#     = [(Q2-Q1)/((Q1+Q2)/2)] / [(I2-I1)/((I1+I2)/2)]
#
# 收入弹性揭示了商品的性质：
#
# 1. YED > 1：奢侈品/高档品 (Luxury Goods)
#    - 收入增加1%，需求增加超过1%
#    - 需求对收入变化非常敏感
#    - 例如：名牌服装、高端餐厅、国际旅游、珠宝首饰
#    - 经济繁荣时销量大增，衰退时销量骤降
#
# 2. 0 < YED < 1：必需品 (Normal Necessities)
#    - 收入增加1%，需求增加但小于1%
#    - 需求对收入变化不太敏感
#    - 例如：食品、基本服装、水电费、日常交通
#    - 恩格尔定律：随着收入增加，食品支出占比下降
#
# 3. YED < 0：劣等品 (Inferior Goods)
#    - 收入增加，需求反而减少
#    - 消费者收入提高后会转向购买更好的替代品
#    - 例如：方便面（相对于餐厅就餐）、二手衣物、公交（相对于私家车）
#    - 注意：劣等品不等于"劣质品"，只是经济术语
#
# 【恩格尔系数】
# 恩格尔系数 = 食品支出 / 总支出
# 联合国标准：
# - 恩格尔系数 > 60%：贫困
# - 50%-60%：温饱
# - 40%-50%：小康
# - 30%-40%：富裕
# - < 30%：最富裕
#
# 任务：
# 1. 计算交叉价格弹性
# 2. 计算收入弹性
# 3. 根据弹性值分类商品关系
# 4. 根据收入弹性分类商品类型
#
# HINT1: 使用中点法计算弹性
# HINT2: 交叉弹性符号决定替代/互补关系
# HINT3: 收入弹性符号和大小共同决定商品类型

