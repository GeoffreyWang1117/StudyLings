# 【核心概念】
#
# 一、百分比变化（Percentage Change）
# 百分比变化是衡量变量相对变化的标准方法。
# 公式：百分比变化 = (新值 - 旧值) / 旧值 × 100
#
# 应用场景：
# - GDP增长率：(本年GDP - 去年GDP) / 去年GDP × 100
# - 通货膨胀率：(本期物价指数 - 上期物价指数) / 上期物价指数 × 100
# - 股票涨跌幅：(现价 - 原价) / 原价 × 100
#
# 二、年利率与月利率的转换
# 由于复利效应，年利率和月利率之间不是简单的12倍关系。
# 等效月利率公式：月利率 = (1 + 年利率)^(1/12) - 1
#
# 推导过程：
# 设年利率为r_annual，月利率为r_monthly
# 复利条件下：(1 + r_monthly)^12 = 1 + r_annual
# 两边开12次方：1 + r_monthly = (1 + r_annual)^(1/12)
# 因此：r_monthly = (1 + r_annual)^(1/12) - 1
#
# 注意：这与简单除以12的结果不同！
# 例如：年利率12%，简单计算月利率=1%，但等效月利率≈0.949%
#
# 三、复合增长（Compound Growth）
# 复合增长考虑了"利滚利"效应，是经济学中描述长期增长的标准方法。
# 公式：终值 = 初始值 × (1 + 增长率)^期数
#
# 应用场景：
# - 储蓄增长：本金 × (1 + 利率)^年数
# - 经济增长：初始GDP × (1 + 增长率)^年数
# - 人口预测：初始人口 × (1 + 增长率)^年数
#
# 【72法则】
# 一个有趣的经验法则：资金翻倍所需年数 ≈ 72 / 年利率(%)
# 例如：年利率6%，翻倍约需72/6=12年
