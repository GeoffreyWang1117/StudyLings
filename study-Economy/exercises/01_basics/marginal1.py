# 说明：
# 本练习将学习经济学中最重要的分析方法之一：边际分析。
# "边际"（Marginal）指的是"额外增加一单位"所带来的变化。
#
# 【理论背景】
# 边际分析是经济学的核心思维方式。经济学家不问"要不要做某事"，
# 而是问"要不要再多做一点"。这种思维方式揭示了最优决策的本质：
# 在边际上权衡得失。
#
# 【核心概念】
#
# ============================================
# 一、边际收益 (Marginal Revenue, MR)
# ============================================
# 定义：多卖出一单位产品所增加的总收益
# 公式：MR = ΔTR / ΔQ = dTR / dQ
#
# 其中：
# - TR (Total Revenue): 总收益 = 价格 × 销量 = P × Q
# - ΔTR: 总收益的变化量
# - ΔQ: 销量的变化量（通常为1）
#
# 在完全竞争市场中：MR = P（价格）
# 在垄断市场中：MR < P（因为增加销量需要降价）
#
# 例如：
# 销量从10增加到11，总收益从1000增加到1080
# MR = (1080 - 1000) / (11 - 10) = 80
#
# ============================================
# 二、边际成本 (Marginal Cost, MC)
# ============================================
# 定义：多生产一单位产品所增加的总成本
# 公式：MC = ΔTC / ΔQ = dTC / dQ
#
# 其中：
# - TC (Total Cost): 总成本 = 固定成本 + 可变成本 = FC + VC
# - ΔTC: 总成本的变化量
# - ΔQ: 产量的变化量
#
# 边际成本曲线通常呈U型：
# - 初期：规模效应，MC递减
# - 后期：边际报酬递减规律，MC递增
#
# 例如：
# 产量从100增加到101，总成本从5000增加到5045
# MC = (5045 - 5000) / (101 - 100) = 45
#
# ============================================
# 三、利润最大化原则
# ============================================
# 核心定理：利润最大化发生在 MR = MC 时
#
# 推导：
# 利润 π = TR - TC
# 对Q求导：dπ/dQ = dTR/dQ - dTC/dQ = MR - MC
#
# 利润最大化条件：dπ/dQ = 0
# 即：MR = MC
#
# 直觉理解：
# - 若 MR > MC：多生产一单位能增加利润，应该增产
# - 若 MR < MC：多生产一单位会减少利润，应该减产
# - 若 MR = MC：达到最优产量，利润最大化
#
# ============================================
# 四、边际效用与消费者选择
# ============================================
# 边际效用 (Marginal Utility, MU)：
# 多消费一单位商品带来的额外满足感（效用）
#
# 边际效用递减规律：
# 随着消费量增加，每增加一单位带来的满足感递减
#
# 消费者均衡条件：
# MUa/Pa = MUb/Pb = ... = MUn/Pn
# 即：每一元钱花在不同商品上获得的边际效用相等
#
# 任务：
# 1. 计算边际收益
# 2. 计算边际成本
# 3. 找到利润最大化产量
# 4. 计算利润
#
# HINT1: MR = ΔTR/ΔQ, MC = ΔTC/ΔQ
# HINT2: 使用离散方法计算：MR_i = (TR_{i+1} - TR_i) / (Q_{i+1} - Q_i)
# HINT3: 利润最大化点是 |MR - MC| 最小的位置

