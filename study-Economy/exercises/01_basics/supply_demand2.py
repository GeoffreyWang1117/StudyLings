# 【理论背景】
# 市场均衡（Market Equilibrium）是微观经济学的核心概念之一。
# 当市场达到均衡时，供给量等于需求量，市场上既没有过剩也没有短缺。
# 此时的价格称为"均衡价格"（Equilibrium Price），
# 对应的数量称为"均衡数量"（Equilibrium Quantity）。
#
# 【市场均衡的含义】
# 1. 均衡是一种"稳态"：一旦达到均衡，在没有外部干预的情况下，
#    市场价格和数量将保持不变。
# 2. 市场具有自我调节能力：
#    - 若价格高于均衡价格 → 供过于求 → 价格下降
#    - 若价格低于均衡价格 → 供不应求 → 价格上升
#
# 【均衡的数学求解】
# 给定供给函数和需求函数，令 Qs = Qd 即可求得均衡点。
#
# 本练习使用的供需函数：
# - 供给函数: Qs = -10 + 2P
# - 需求函数: Qd = 100 - 3P
#
# 均衡求解过程：
# 令 Qs = Qd：
#     -10 + 2P = 100 - 3P
#     2P + 3P = 100 + 10
#     5P = 110
#     P* = 22（均衡价格）
#
# 将 P* 代入任一函数求均衡数量：
#     Q* = -10 + 2 × 22 = -10 + 44 = 34（均衡数量）
#     验证：Q* = 100 - 3 × 22 = 100 - 66 = 34 ✓
#
# 【市场状态分析】
# 当价格偏离均衡价格时，市场会出现失衡状态：
#
# 1. 过剩（Surplus）：Qs > Qd
#    - 发生条件：价格高于均衡价格
#    - 例如：当 P = 30 时
#      Qs = -10 + 2×30 = 50
#      Qd = 100 - 3×30 = 10
#      过剩量 = 50 - 10 = 40
#    - 市场反应：卖方降价销售，价格趋向下降
#
# 2. 短缺（Shortage）：Qs < Qd
#    - 发生条件：价格低于均衡价格
#    - 例如：当 P = 10 时
#      Qs = -10 + 2×10 = 10
#      Qd = 100 - 3×10 = 70
#      短缺量 = 70 - 10 = 60
#    - 市场反应：买方抬价购买，价格趋向上升
#
# 3. 均衡（Equilibrium）：Qs = Qd
#    - 发生条件：价格等于均衡价格
#    - 市场处于稳定状态
#
