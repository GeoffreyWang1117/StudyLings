# 说明：
# 公共品理论是公共经济学的基石之一，解释了为什么某些商品需要由政府提供，
# 以及如何确定公共品的最优供给水平。
#
# 【理论背景】
# Paul Samuelson（1954）在其经典论文中首次严格定义了公共品的特性，
# 并推导出公共品最优供给的条件（Samuelson条件）。
#
# 【商品的两个关键特性】
#
# 1. 竞争性（Rivalry）
#    - 一个人消费是否减少他人可消费的数量？
#    - 竞争性：苹果（我吃了你就不能吃）
#    - 非竞争性：电视信号（我看不影响你看）
#
# 2. 排他性（Excludability）
#    - 能否阻止未付费者消费？
#    - 可排他：电影院（不买票不能进）
#    - 不可排他：路灯（无法阻止路人享用）
#
# 【四种商品分类】
#
#                   可排他          不可排他
#              ┌──────────────┬──────────────┐
#     竞争性   │   私人品      │   公共资源    │
#              │ (Private)     │ (Common)      │
#              │ 例：食物      │ 例：海洋渔场  │
#              ├──────────────┼──────────────┤
#     非竞争   │   俱乐部品    │   纯公共品    │
#              │ (Club)        │ (Public)      │
#              │ 例：有线电视  │ 例：国防      │
#              └──────────────┴──────────────┘
#
# 1. 私人品（Private Goods）
#    - 竞争性 + 可排他
#    - 市场机制有效运作
#    - 例：食物、衣服、汽车
#
# 2. 纯公共品（Pure Public Goods）
#    - 非竞争性 + 不可排他
#    - 市场失灵，需政府提供
#    - 例：国防、灯塔、空气质量
#
# 3. 俱乐部品（Club Goods）
#    - 非竞争性 + 可排他
#    - 可通过收费机制私人提供
#    - 例：有线电视、健身房、高速公路（不拥堵时）
#
# 4. 公共资源（Common Resources）
#    - 竞争性 + 不可排他
#    - 面临"公地悲剧"问题
#    - 例：海洋渔场、公共草地、地下水
#
# 【公共品的市场失灵】
#
# 为什么市场无法有效提供公共品？
#
# 1. 搭便车问题（Free-rider Problem）
#    由于不可排他，每个人都有激励不付费而享用他人提供的公共品。
#    理性人的最优策略是：让别人提供，我免费享用。
#    结果：人人都想搭便车，没人愿意提供 → 供给不足
#
# 2. 偏好表露问题
#    即使愿意付费，人们也有激励低报自己对公共品的估值，
#    以期减少自己的负担。
#    结果：无法了解真实需求 → 无法确定最优供给
#
# 【Samuelson最优供给条件】
#
# 对于私人品：每个人的MRS = MRT（市场价格机制实现）
# 对于公共品：Σ MRSᵢ = MRT
#
# 推导：
# 设社会有N个人，公共品数量为G，私人品数量为X
# 每个人的效用函数：Uᵢ(xᵢ, G)
# 生产可能性边界：F(X, G) = 0
#
# 社会计划者问题：
# max Σ αᵢUᵢ(xᵢ, G)
# s.t. F(Σxᵢ, G) = 0
#
# 一阶条件推导出：
# Σ MRSᵢ = Σ (∂Uᵢ/∂G)/(∂Uᵢ/∂x) = MRT = ∂F/∂G / ∂F/∂X
#
# 经济含义：
# - 公共品的边际成本应等于所有人边际收益之和
# - 因为公共品非竞争，一单位公共品同时给所有人带来收益
# - 与私人品不同，公共品需要"垂直加总"需求曲线
#
# 【Lindahl均衡】
# Erik Lindahl（1919）提出的理想化解决方案：
#
# 每个人支付与其边际收益成比例的"个性化价格"
# 人i支付的税价：tᵢ = MRSᵢ
# 满足预算平衡：Σ tᵢ = MC
#
# 在Lindahl均衡中：
# 1. 每个人面对的边际支付等于边际收益，实现帕累托最优
# 2. 公共品供给达到Samuelson条件
# 3. 高评价者多付，低评价者少付
#
# 问题：需要知道每个人的真实偏好，但人们有激励隐瞒
#
# 【私人自愿提供】
# 如果公共品由私人自愿提供会怎样？
#
# 每个人只考虑自己的边际收益（忽略对他人的正外部性）
# 私人最优条件：MRSᵢ = MC
# 社会最优条件：Σ MRSᵢ = MC
#
# 结果：私人提供的数量 < 社会最优数量
# 差距取决于人数和外部性的大小
#
# 【热心肠捐赠模型（Warm-glow Giving）】
# James Andreoni（1989）提出：
#
# 人们捐赠不仅因为利他主义（关心公共品总量），
# 也因为捐赠本身带来满足感（"热心肠"）。
#
# 效用函数：Uᵢ = u(cᵢ, G, gᵢ)
# 其中：
# - cᵢ: 私人消费
# - G: 公共品总量（所有人贡献之和）
# - gᵢ: 自己的捐赠（提供热心肠效用）
#
# 这解释了为什么现实中人们会捐赠，即使他们可以搭便车
