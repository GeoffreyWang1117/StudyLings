# 说明：
# 社会福利函数是规范经济学的核心工具，用于将个人效用汇总为社会整体福利，
# 为政策评估和收入再分配提供理论基础。
#
# 【理论背景】
# 福利经济学研究如何评价经济状态的好坏以及如何改善社会福利。
# 核心问题：如何从个人效用推导出社会偏好？
#
# 【福利经济学基本定理】
#
# 第一福利定理（"看不见的手"定理）：
# 在完全竞争市场中，任何竞争均衡都是帕累托最优的。
# - 前提：完全竞争、无外部性、信息完全、产权明确
# - 含义：市场机制本身可以实现效率
# - 局限：未涉及公平问题
#
# 第二福利定理：
# 在凸偏好和凸技术下，任何帕累托最优配置都可以通过以下方式实现：
# 1. 适当的初始资源再分配（一次性总额转移）
# 2. 让市场机制运作
# - 含义：效率与公平可以分离处理
# - 局限：一次性总额转移实践中难以实现
#
# 【帕累托最优的局限】
# 帕累托标准只是效率标准，可能存在极度不公平的帕累托最优：
# - (100, 0) 和 (0, 100) 都是帕累托最优
# - (99, 1) 可能比 (50, 50) 更"帕累托"
# 因此需要社会福利函数来做更完整的评价
#
# 【社会福利函数（Social Welfare Function, SWF）】
# 将所有个人效用汇总为单一社会福利值的函数：
# W = W(U₁, U₂, ..., Uₙ)
#
# 性质（通常假设）：
# 1. 帕累托性：如果每个人效用不减，至少一人增加，则社会福利增加
# 2. 匿名性：交换任意两人的效用，社会福利不变
# 3. 连续性和可微性
#
# 【常见社会福利函数】
#
# 1. 功利主义/边沁主义（Utilitarian/Benthamite）
#    W = Σ Uᵢ（效用之和）
#
#    特点：
#    - 关注总效用最大化
#    - 个人间效用可完全替代
#    - 可能忽视分配公平
#    - 社会边际效用权重都等于1
#
#    代表人物：Jeremy Bentham, John Stuart Mill
#
# 2. 罗尔斯主义（Rawlsian）
#    W = min(Uᵢ)（最差者的效用）
#
#    特点：
#    - 关注最弱势群体（差别原则）
#    - 极端的公平偏好
#    - 来自"无知之幕"思想实验
#    - 只有提高最差者才能提高社会福利
#
#    代表人物：John Rawls《正义论》
#
# 3. 纳什社会福利（Nash）
#    W = Π Uᵢ（效用之积）
#    或等价地：W = Σ log(Uᵢ)
#
#    特点：
#    - 介于功利主义和罗尔斯主义之间
#    - 对数形式给予低效用者更高边际权重
#    - 满足某些公理化要求
#
# 4. 阿特金森社会福利函数（Atkinson）
#    W = (1/(1-ε)) × Σ Uᵢ^(1-ε)   当 ε ≠ 1
#    W = Σ log(Uᵢ)                 当 ε = 1
#
#    特点：
#    - ε 是不平等厌恶参数
#    - ε = 0：功利主义
#    - ε → ∞：罗尔斯主义
#    - ε = 1：纳什社会福利
#    - 灵活性强，可调节公平偏好程度
#
#    代表人物：Anthony Atkinson
#
# 【社会无差异曲线】
# 在U₁-U₂平面上，社会福利相等的点的轨迹
# - 功利主义：45度直线（斜率=-1）
# - 罗尔斯主义：直角形（最差者决定）
# - 阿特金森：凸向原点的曲线（ε越大越凸）
#
# 【阿罗不可能定理（Arrow's Impossibility Theorem）】
# Kenneth Arrow（1951）证明：不存在满足以下所有条件的社会福利函数：
# 1. 普遍域（任何个人偏好组合都可以汇总）
# 2. 帕累托性
# 3. 非独裁性（不由单个人决定）
# 4. 二元独立性（两方案的社会排序只取决于个人对这两方案的排序）
#
# 含义：任何社会决策机制都必须放弃某个条件
#
# 【最优再分配】
#
# 问题：政府应该进行多少再分配？
#
# 权衡：
# - 收益：改善公平，提高边际效用更高者的消费
# - 成本：效率损失（激励扭曲、无谓损失）
#
# Okun的漏桶（Leaky Bucket）隐喻：
# 从富人向穷人转移收入就像用漏桶运水
# - 桶会漏：转移1元，穷人可能只收到0.7元
# - 损失来源：征税的无谓损失、管理成本、激励扭曲
#
# 最优再分配条件：
# 边际公平收益 = 边际效率损失
