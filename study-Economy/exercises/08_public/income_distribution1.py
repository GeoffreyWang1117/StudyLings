# 说明：
# 收入分配研究社会财富如何在不同群体间分布，不平等度量为政策评估提供客观依据。
# 这是公共经济学和发展经济学的核心议题之一。
#
# 【理论背景】
# 不平等既是经济问题，也是社会问题。
# 过度不平等可能导致：社会不稳定、经济增长受阻、代际流动性下降。
#
# 【不平等度量的基本原则】
#
# 理想的不平等度量应满足以下公理：
#
# 1. 匿名性（Anonymity）
#    交换任意两人收入，不平等度不变
#    只关心分布，不关心谁有多少
#
# 2. 规模不变性（Scale Independence）
#    所有人收入同比例变化，不平等度不变
#    衡量的是相对不平等，而非绝对差异
#
# 3. 人口原则（Population Principle）
#    社会复制不改变不平等度
#    不平等度与人口规模无关
#
# 4. 转移原则（Transfer Principle/Pigou-Dalton）
#    从富人向穷人转移收入（不改变排序）应降低不平等
#    这是最重要的公理
#
# 【洛伦兹曲线（Lorenz Curve）】
# Max Lorenz（1905）提出的图形表示方法
#
# 横轴：累积人口比例（从0%到100%）
# 纵轴：累积收入比例
#
# 绘制方法：
# 1. 将人口按收入从低到高排序
# 2. 计算前x%人口的收入占总收入的比例
# 3. 描点连线
#
# 解读：
# - 45度线：完全平等（每x%人口拥有x%收入）
# - 曲线越凸向右下角，不平等越严重
# - 曲线与45度线之间的面积反映不平等程度
#
# 洛伦兹优势（Lorenz Dominance）：
# 如果A的洛伦兹曲线完全在B之上（更接近45度线），
# 则A的分配优于B（对任何满足转移原则的指标）
#
# 【基尼系数（Gini Coefficient）】
# Corrado Gini（1912）提出的最常用不平等指标
#
# 定义：
# G = 洛伦兹曲线与45度线之间面积 / 45度线下方总面积
# G = 2 × (洛伦兹曲线与45度线之间面积)
# G = A / (A + B)，其中A是曲线上方面积，B是曲线下方面积
#
# 取值范围：
# - G = 0：完全平等
# - G = 1：完全不平等（一人拥有全部）
#
# 计算公式：
# G = (2 × Σᵢ i × yᵢ) / (n × Σ yᵢ) - (n+1)/n
# 其中 yᵢ 按升序排列
#
# 各国基尼系数（约2020年）：
# - 北欧国家：0.25-0.30
# - 德国、法国：0.30-0.35
# - 美国：0.40-0.45
# - 中国：0.45-0.50
# - 南非、巴西：0.55-0.65
#
# 【泰尔指数（Theil Index）】
# Henri Theil基于信息论提出的不平等指标
#
# 公式：
# T = (1/n) × Σ (yᵢ/μ) × log(yᵢ/μ)
#
# 其中 μ = 平均收入
#
# 优点：
# 1. 可分解性（Decomposability）
#    总不平等 = 组内不平等 + 组间不平等
#    T = T_within + T_between
#
#    这使得可以分析不平等的来源：
#    - 城乡差距贡献多少？
#    - 教育差异贡献多少？
#
# 2. 满足各种公理性质
#
# 取值：
# - T = 0：完全平等
# - T > 0：存在不平等（无上限）
#
# 【变异系数（Coefficient of Variation）】
# CV = σ / μ = 标准差 / 平均值
#
# 简单直观，但对极端值敏感
#
# 【百分位比（Percentile Ratios）】
# 常用指标：
# - P90/P10：高收入与低收入的比值
# - P50/P10：中位数与低收入的比值
# - P90/P50：高收入与中位数的比值
#
# 优点：直观易懂，不受极端值影响
#
# 【帕尔马比率（Palma Ratio）】
# Jose Gabriel Palma提出：
# Palma = 最富10%收入份额 / 最穷40%收入份额
#
# 理由：中间50%的收入份额在各国相对稳定（约50%）
# 不平等主要体现在两端的差异
#
# 【库兹涅茨曲线（Kuznets Curve）】
# Simon Kuznets（1955）假说：
# 经济发展与不平等呈倒U形关系
#
# - 发展初期：不平等上升（劳动力从农业转向工业）
# - 发展后期：不平等下降（教育普及、再分配政策）
#
# 实证支持有限，可能需要政策干预才能实现下降
#
