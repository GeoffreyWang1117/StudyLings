# TOPIC: 蒙代尔-弗莱明模型
#
# 说明：
# 蒙代尔-弗莱明模型（Mundell-Fleming Model）是开放经济下的IS-LM模型，
# 由罗伯特·蒙代尔（Robert Mundell）和马库斯·弗莱明（Marcus Fleming）
# 在1960年代分别独立发展。蒙代尔因此获得1999年诺贝尔经济学奖。
#
# 【模型的理论背景】
# 封闭经济IS-LM模型无法分析：
# - 汇率如何影响经济
# - 资本流动如何影响政策效果
# - 不同汇率制度下政策效果的差异
#
# M-F模型通过引入国际收支约束来解决这些问题。
#
# 【模型基本方程】
#
# 1. IS曲线（产品市场均衡）
#    Y = C(Y-T) + I(r) + G + NX(Y, Y*, RER)
#
#    净出口函数：
#    NX = NX₀ - m·Y + m_RER·RER + m_Y*·Y*
#
#    其中：
#    - m: 边际进口倾向（收入增加导致进口增加）
#    - m_RER: 实际汇率弹性（贬值改善净出口）
#    - RER: 实际汇率（上升表示贬值）
#
# 2. LM曲线（货币市场均衡）
#    M/P = L(Y, r) = L₀ + L_Y·Y - L_r·r
#
#    实际货币供给 = 货币需求
#
# 3. BP曲线（国际收支均衡）
#    CA + KA = 0
#    NX(Y, RER) + KF(r - r*) = 0
#
#    资本完全流动时：r = r*
#    （国内利率必须等于世界利率，否则无限资本流动）
#
# 【关键假设】
# 1. 小国假设：本国无法影响世界利率r*
# 2. 价格粘性：短期内价格水平P固定
# 3. 完全资本流动：r = r*（BP曲线水平）
# 4. 静态预期：预期汇率不变
#
# 【政策效果分析（资本完全流动）】
#
# ┌─────────────┬──────────────────┬──────────────────┐
# │   政策      │    固定汇率      │    浮动汇率      │
# ├─────────────┼──────────────────┼──────────────────┤
# │ 财政扩张    │ 有效（M内生增加）│ 无效（汇率升值   │
# │ (G↑)        │ Y↑, M↑          │ 挤出净出口）     │
# ├─────────────┼──────────────────┼──────────────────┤
# │ 货币扩张    │ 无效（储备流失   │ 有效（汇率贬值   │
# │ (M↑)        │ 抵消货币增加）   │ 刺激净出口）     │
# └─────────────┴──────────────────┴──────────────────┘
#
# 【固定汇率下的调整机制】
# 货币扩张 → 利率下降 → 资本外流 → 外汇市场卖本币买外币
# → 央行为维持汇率必须卖出外汇储备 → 货币供给减少
# → 最终回到初始均衡，政策无效
#
# 【浮动汇率下的调整机制】
# 货币扩张 → 利率下降 → 资本外流 → 本币贬值
# → 净出口增加 → IS右移 → 产出增加，利率回到r*
#
# 【不可能三角（Impossible Trinity）】
# 又称三元悖论（Trilemma）
#
# 以下三者最多只能同时实现两个：
# 1. 固定汇率
# 2. 资本自由流动
# 3. 独立的货币政策
#
# 各国选择：
# - 美国：浮动汇率 + 资本流动 + 独立货币政策
# - 中国（历史上）：固定汇率 + 资本管制 + 独立货币政策
# - 欧元区成员国：固定汇率 + 资本流动 + 放弃货币政策
# - 香港：固定汇率 + 资本流动 + 放弃货币政策
#
