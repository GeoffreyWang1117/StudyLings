#
# 说明：
# 国际收支平衡表（Balance of Payments, BOP）记录一国在特定时期内
# 与世界其他地区之间的全部经济往来。它是开放经济宏观分析的核心工具。
#
# 【国际收支的理论基础】
# 国际收支基于"复式记账"原则：每笔交易都记录在借方和贷方。
# - 贷方（+）：导致外汇流入的交易（出口、资本流入）
# - 借方（-）：导致外汇流出的交易（进口、资本流出）
#
# 【国际收支账户结构（IMF第六版手册）】
#
# 1. 经常账户（Current Account, CA）
#    记录与实际资源流动相关的交易
#    CA = 商品贸易 + 服务贸易 + 初次收入 + 二次收入
#
#    (a) 商品贸易：有形商品的进出口
#    (b) 服务贸易：运输、旅游、金融、知识产权等
#    (c) 初次收入：投资收益（利息、股息）、员工报酬
#    (d) 二次收入：经常性转移（侨汇、援助、国际组织会费）
#
# 2. 资本账户（Capital Account, KA）
#    记录资本转移和非生产性非金融资产交易
#    - 资本转移：债务减免、移民转移
#    - 非生产性资产：专利、商标购买
#    (金额通常较小，有时与金融账户合并)
#
# 3. 金融账户（Financial Account, FA）
#    记录金融资产和负债的变化
#    FA = 直接投资 + 证券投资 + 金融衍生品 + 其他投资 + 储备资产
#
#    (a) 直接投资（FDI）：控制性投资（≥10%股权）
#    (b) 证券投资：股票、债券（<10%股权）
#    (c) 金融衍生品：期货、期权等
#    (d) 其他投资：贸易信贷、贷款、存款
#    (e) 储备资产：央行持有的外汇储备变化
#
# 【国际收支恒等式】
# CA + KA + FA + 误差与遗漏 = 0
#
# 实务中，由于统计困难，存在"误差与遗漏"项
#
# 【储蓄-投资恒等式】
# 从国民收入核算角度：
# Y = C + I + G + NX
# Y - C - G = I + NX
# S = I + NX
# 因此：CA ≈ NX = S - I = (S_p - I) + (T - G)
#
# 其中：
# - S_p: 私人储蓄
# - I: 投资
# - T - G: 政府储蓄（财政盈余）
#
# 【双赤字假说（Twin Deficits）】
# 如果私人部门储蓄-投资大致平衡：
# CA ≈ T - G
# 财政赤字往往伴随经常账户赤字
# 美国1980年代和2000年代的经验支持此假说
#
# 【国际投资头寸（IIP）】
# 存量概念，反映某时点一国对外金融资产与负债
# NIIP = 对外资产 - 对外负债
# ΔNIIP = CA + 估值效应
#
# 【马歇尔-勒纳条件】
# 贬值能否改善贸易收支？
# 需满足：|η_x| + |η_m| > 1
# 其中η_x和η_m分别是出口和进口的价格弹性
#
# 如果弹性条件不满足，贬值初期可能恶化贸易收支（J曲线效应）
#
