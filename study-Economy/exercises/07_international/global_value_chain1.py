# TOPIC: 全球价值链
#
# ============================================================================
# 理论背景
# ============================================================================
#
# 全球价值链（Global Value Chain, GVC）反映了生产过程的国际碎片化：
# 一个产品的设计、零部件生产、组装、营销可能分布在多个国家。
#
# 传统贸易 vs GVC贸易：
# ┌─────────────────────────────────────────────────────────────────────────┐
# │ 传统贸易（李嘉图时代）               │ GVC贸易（21世纪）               │
# ├─────────────────────────────────────┼────────────────────────────────┤
# │ 最终产品跨境                         │ 中间品多次跨境                  │
# │ 一国完成全部生产                     │ 多国参与生产不同环节            │
# │ 总值贸易 ≈ 增加值贸易               │ 总值贸易 >> 增加值贸易          │
# │ 垂直一体化生产                       │ 垂直专业化分工                  │
# └─────────────────────────────────────┴────────────────────────────────┘
#
# ============================================================================
# 核心概念
# ============================================================================
#
# 1. 垂直专业化（Vertical Specialization, VS）
#    ┌─────────────────────────────────────────────────────────────────────┐
#    │ 定义：出口中包含的进口中间品价值                                    │
#    │                                                                      │
#    │ VS = 出口中的进口中间品 / 总出口                                    │
#    │                                                                      │
#    │ 经济含义：                                                           │
#    │ - 衡量一国出口对进口投入品的依赖程度                                │
#    │ - VS高 → 深度嵌入国际生产网络                                       │
#    │ - VS低 → 自给自足或处于价值链上游                                   │
#    │                                                                      │
#    │ 代表性研究：Hummels, Ishii & Yi (2001)                              │
#    └─────────────────────────────────────────────────────────────────────┘
#
# 2. GVC参与度（GVC Participation）
#    ┌─────────────────────────────────────────────────────────────────────┐
#    │ 前向参与度（Forward Participation）：                                │
#    │   = 本国增加值被他国出口使用 / 本国总出口                           │
#    │   例：中国出口钢材→韩国造船→出口全球                               │
#    │        中国钢材增加值在韩国船舶出口中                               │
#    │                                                                      │
#    │ 后向参与度（Backward Participation）：                               │
#    │   = 本国出口中的外国增加值 / 本国总出口                             │
#    │   例：中国出口手机中包含的日韩芯片价值                              │
#    │                                                                      │
#    │ 总参与度 = 前向参与度 + 后向参与度                                  │
#    └─────────────────────────────────────────────────────────────────────┘
#
# 3. GVC位置指数（GVC Position Index）
#    ┌─────────────────────────────────────────────────────────────────────┐
#    │ Position = ln(1 + Forward) - ln(1 + Backward)                       │
#    │                                                                      │
#    │ 解释：                                                               │
#    │ - Position > 0：上游位置（提供中间品，如原材料、零部件）            │
#    │ - Position < 0：下游位置（组装最终品，如代工厂）                    │
#    │ - Position ≈ 0：中间位置                                            │
#    │                                                                      │
#    │ 典型分布：                                                           │
#    │   上游（+）: 澳大利亚（资源）、日本（核心零部件）                   │
#    │   下游（-）: 中国（组装）、墨西哥（加工出口）                       │
#    └─────────────────────────────────────────────────────────────────────┘
#
# ============================================================================
# 增加值贸易分析框架
# ============================================================================
#
# Johnson & Noguera (2012) 增加值出口（VAX）：
#
# 总出口的分解：
# ┌─────────────────────────────────────────────────────────────────────────┐
# │ 总出口 = 国内增加值(DVA) + 外国增加值(FVA)                              │
# │                                                                          │
# │ 国内增加值进一步分解：                                                   │
# │ DVA = 直接被吸收的DVA + 间接出口的DVA + 返回的DVA                       │
# │                                                                          │
# │ 增加值出口率：                                                           │
# │ VAX_Ratio = 出口中的国内增加值 / 总出口                                 │
# │           = 1 - FVA_Share                                               │
# │                                                                          │
# │ 双边VAX可能与总值贸易差异很大：                                         │
# │ - iPhone出口：中国对美总值顺差大，但增加值顺差小                        │
# │ - 大部分增加值归属于设计国（美国）和零部件国（日韩）                    │
# └─────────────────────────────────────────────────────────────────────────┘
#
# 投入产出分析（Input-Output Analysis）：
# ┌─────────────────────────────────────────────────────────────────────────┐
# │ 里昂惕夫模型：                                                          │
# │   X = AX + Y                                                            │
# │   X = (I - A)^{-1} × Y = L × Y                                         │
# │                                                                          │
# │ 其中：                                                                   │
# │   X = 总产出向量                                                        │
# │   A = 直接消耗系数矩阵                                                  │
# │   Y = 最终需求向量                                                      │
# │   L = (I - A)^{-1} = 里昂惕夫逆矩阵                                    │
# │                                                                          │
# │ 增加值出口计算：                                                         │
# │   VAX = v × L × E                                                       │
# │                                                                          │
# │ 其中：                                                                   │
# │   v = 增加值系数向量（增加值/总产出）                                   │
# │   E = 出口向量                                                          │
# └─────────────────────────────────────────────────────────────────────────┘
#
# ============================================================================
# 上游度与下游度
# ============================================================================
#
# Antràs & Chor (2013) 上游度指数：
# ┌─────────────────────────────────────────────────────────────────────────┐
# │ 上游度（Upstreamness）：衡量产品距离最终消费的"距离"                  │
# │                                                                          │
# │ 简化计算：                                                               │
# │   U = 1 / Final_Use_Share                                               │
# │                                                                          │
# │ 其中：Final_Use_Share = 直接进入最终需求的比例                          │
# │                                                                          │
# │ 解释：                                                                   │
# │ - 采矿业：上游度高（多次加工后才到消费者）                              │
# │ - 零售业：上游度低（直接面对消费者）                                    │
# │                                                                          │
# │ 完整公式（递归）：                                                       │
# │   Uᵢ = 1 + Σⱼ (dᵢⱼ/Yᵢ) × Uⱼ                                            │
# │   其中dᵢⱼ是i部门对j部门的中间品销售                                     │
# └─────────────────────────────────────────────────────────────────────────┘
#
# ============================================================================
# GVC收入
# ============================================================================
#
# GVC收入衡量一国从参与全球价值链中实际获得的收益：
# ┌─────────────────────────────────────────────────────────────────────────┐
# │ GVC_Income = Gross_Exports × (1 - FVA_Share) + Returned_DVA             │
# │                                                                          │
# │ 简化版：                                                                 │
# │ GVC_Income = Gross_Exports × (1 - Foreign_Value_Share + Returned_Share) │
# │                                                                          │
# │ 其中：                                                                   │
# │ - Foreign_Value_Share：外国增加值份额                                   │
# │ - Returned_Share：出口后返回本国的增加值份额                            │
# │                                                                          │
# │ 意义：                                                                   │
# │ - 区分"卖了多少"和"赚了多少"                                          │
# │ - 代工型经济体：总出口高，GVC收入低                                    │
# │ - 创新型经济体：GVC收入/总出口比值高                                   │
# └─────────────────────────────────────────────────────────────────────────┘
#
# ============================================================================
# 对贸易统计的影响
# ============================================================================
#
# 总值贸易统计的问题：
# ┌─────────────────────────────────────────────────────────────────────────┐
# │ 1. 重复计算：                                                           │
# │    - 同一增加值随中间品多次跨境被重复计入                               │
# │    - 全球贸易/全球GDP比率虚高                                          │
# │                                                                          │
# │ 2. 双边余额失真：                                                        │
# │    - 中国对美贸易顺差（总值）≈ 3000亿美元                              │
# │    - 中国对美贸易顺差（增加值）≈ 1500亿美元                            │
# │    - 原因：中国出口含大量日韩台进口零部件                              │
# │                                                                          │
# │ 3. 政策误导：                                                            │
# │    - 基于总值数据的贸易战可能误伤"无辜"第三国                          │
# │    - 汇率变动效果被放大（多次跨境价格传递）                            │
# └─────────────────────────────────────────────────────────────────────────┘
#
