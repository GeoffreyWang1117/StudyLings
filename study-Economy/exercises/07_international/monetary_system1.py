# 国际货币体系（International Monetary System, IMS）是全球汇率安排、国际支付清算
# 和储备资产管理的制度框架。它决定了各国货币之间的交换方式和国际收支调节机制。
#
# ============================================================================
# 历史演进
# ============================================================================
#
# 1. 金本位时期（1870-1914）
#    ┌─────────────────────────────────────────────────────────────────────┐
#    │ 核心机制：价格-铸币流动机制（Price-Specie Flow Mechanism）           │
#    │                                                                      │
#    │ 调节过程：                                                           │
#    │   贸易逆差 → 黄金流出 → 货币供应↓ → 价格↓ → 出口竞争力↑            │
#    │              ↓                                                       │
#    │   贸易顺差 → 黄金流入 → 货币供应↑ → 价格↑ → 出口竞争力↓            │
#    │                                                                      │
#    │ 优点：汇率稳定、通胀约束、国际收支自动调节                          │
#    │ 缺点：通缩偏向、黄金供应约束、国内目标从属于外部平衡                │
#    │                                                                      │
#    │ 金本位规则（Rules of the Game）：                                    │
#    │ - 央行配合黄金流动调整利率                                          │
#    │ - 逆差国加息，顺差国降息                                            │
#    └─────────────────────────────────────────────────────────────────────┘
#
# 2. 布雷顿森林体系（1944-1971）
#    ┌─────────────────────────────────────────────────────────────────────┐
#    │ 核心安排：                                                           │
#    │ - 美元与黄金挂钩：1盎司黄金 = 35美元                                │
#    │ - 其他货币与美元固定平价，波动幅度±1%                              │
#    │ - IMF提供短期融资支持                                               │
#    │                                                                      │
#    │ 汇率计算：                                                           │
#    │   对美元汇率 = 本国货币金平价 / 美元金平价                          │
#    │             = (X本币/盎司) / (35美元/盎司)                           │
#    │             = X/35 本币/美元                                        │
#    │                                                                      │
#    │ 特里芬困境（Triffin Dilemma）：                                      │
#    │ - 世界经济增长需要更多美元储备                                      │
#    │ - 美元外流 → 美元债务↑ → 对美元黄金可兑换性信心↓                   │
#    │ - 但美国保持顺差 → 全球流动性不足                                   │
#    │                                                                      │
#    │ 崩溃原因：美国黄金储备不足以覆盖海外美元债务                        │
#    │          1971年8月15日尼克松宣布美元与黄金脱钩                       │
#    └─────────────────────────────────────────────────────────────────────┘
#
# 3. 牙买加体系（1976-至今）
#    ┌─────────────────────────────────────────────────────────────────────┐
#    │ 特点：                                                               │
#    │ - 汇率制度多元化：固定、浮动、管理浮动、货币局等                    │
#    │ - 黄金非货币化：SDR成为官方储备资产                                 │
#    │ - 美元仍是主要储备货币（约60%）                                     │
#    │                                                                      │
#    │ 汇率制度分类（IMF）：                                                │
#    │ ┌────────────────┬──────────────────────────────────────┐           │
#    │ │ 制度类型       │ 特征                                 │           │
#    │ ├────────────────┼──────────────────────────────────────┤           │
#    │ │ 硬钉住         │ 货币局、美元化、货币联盟            │           │
#    │ │ 软钉住         │ 传统固定、爬行、水平区间            │           │
#    │ │ 浮动           │ 管理浮动、自由浮动                  │           │
#    │ └────────────────┴──────────────────────────────────────┘           │
#    └─────────────────────────────────────────────────────────────────────┘
#
# ============================================================================
# 最优货币区理论（Optimum Currency Area Theory, OCA）
# ============================================================================
#
# 创始人：蒙代尔（Mundell, 1961）、麦金农（McKinnon, 1963）、凯南（Kenen, 1969）
#
# 核心问题：哪些国家/地区适合采用同一种货币？
#
# OCA标准：
# ┌─────────────────────────────────────────────────────────────────────────┐
# │ 标准                 │ 经济学含义                                       │
# ├─────────────────────┼─────────────────────────────────────────────────┤
# │ 1. 生产要素流动性   │ 劳动力流动可替代汇率调整，吸收非对称冲击       │
# │                      │ 资本流动促进效率但可能加剧危机                  │
# │                      │                                                  │
# │ 2. 经济周期同步性   │ 同步性高→需要类似货币政策                       │
# │                      │ 测量：产出相关系数、需求/供给冲击相关性         │
# │                      │                                                  │
# │ 3. 贸易开放度       │ 开放度高→汇率变动对价格传递快→固定汇率成本低  │
# │                      │ 但汇率工具对调节作用也更大                      │
# │                      │                                                  │
# │ 4. 财政一体化       │ 财政转移可替代汇率调整                          │
# │                      │ 例：美国联邦财政自动稳定器                      │
# │                      │                                                  │
# │ 5. 价格/工资弹性    │ 弹性高→名义汇率调整不必要                       │
# │                      │ 但实际中工资刚性普遍存在                        │
# │                      │                                                  │
# │ 6. 生产多元化       │ 多元化→单一部门冲击影响小                       │
# │                      │ 减少对汇率调整的需求                            │
# └─────────────────────┴─────────────────────────────────────────────────┘
#
# OCA评分函数（综合加权）：
#   OCA_Score = w₁×劳动力流动性 + w₂×周期相关性 + w₃×贸易开放度 + w₄×财政一体化
#
# 欧元区案例：
# - 满足：贸易开放度高、周期相关性（核心国家）
# - 不足：劳动力流动低、财政一体化低、周期不同步（边缘国家）
# - 结果：主权债务危机（2010-2012）
#
# ============================================================================
# 浮动恐惧（Fear of Floating）
# ============================================================================
#
# Calvo和Reinhart（2002）发现：
# - 许多新兴市场声称浮动汇率，但实际频繁干预
# - 表现为：汇率波动低，但储备和利率波动高
#
# 原因：
# 1. 汇率传递效应强 → 担心通胀
# 2. 外币负债（原罪问题）→ 担心资产负债表效应
# 3. 出口竞争力关注
# 4. 锚定预期需要
#
# 识别方法：
# ┌─────────────────────────────────────────────────────────────────────────┐
# │ 变量               │ 浮动汇率     │ 固定汇率     │ "浮动恐惧"  │
# ├───────────────────┼─────────────┼─────────────┼─────────────┤
# │ 汇率波动性         │ 高           │ 低           │ 低           │
# │ 外汇储备波动性     │ 低           │ 高           │ 高           │
# │ 利率波动性         │ 低           │ 高           │ 高           │
# └───────────────────┴─────────────┴─────────────┴─────────────┘
#
# ============================================================================
# 特别提款权（Special Drawing Rights, SDR）
# ============================================================================
#
# 定义：IMF创设的国际储备资产，补充成员国官方储备
#
# SDR价值计算：
#   SDR = Σᵢ (wᵢ × eᵢ)
#
#   其中：wᵢ = 货币i的权重（货币单位数）
#         eᵢ = 货币i对美元汇率
#
# 当前篮子构成（2022年调整后）：
# ┌────────────┬─────────────┬────────────────┐
# │ 货币       │ 权重(%)     │ 加入时间       │
# ├────────────┼─────────────┼────────────────┤
# │ 美元       │ 43.38%      │ 1969年         │
# │ 欧元       │ 29.31%      │ 1999年         │
# │ 人民币     │ 12.28%      │ 2016年         │
# │ 日元       │ 7.59%       │ 1969年         │
# │ 英镑       │ 7.44%       │ 1969年         │
# └────────────┴─────────────┴────────────────┘
#
# ============================================================================
# 外汇储备充足性
# ============================================================================
#
# 为什么持有储备？
# 1. 干预汇率
# 2. 支付进口
# 3. 偿还外债
# 4. 应对资本外逃
# 5. 信心效应
#
# 充足性指标：
# ┌─────────────────────────────────────────────────────────────────────────┐
# │ 指标                    │ 计算公式                │ 推荐水平           │
# ├────────────────────────┼────────────────────────┼───────────────────┤
# │ 进口覆盖月数            │ 储备 / 月进口          │ ≥3个月             │
# │ (传统标准)              │                        │                    │
# │                         │                        │                    │
# │ Greenspan-Guidotti规则  │ 储备 / 短期外债        │ ≥100%              │
# │ (资本账户标准)          │                        │                    │
# │                         │                        │                    │
# │ M2覆盖率                │ 储备 / M2              │ 5%-20%             │
# │ (金融深化标准)          │                        │ (取决于汇率制度)   │
# │                         │                        │                    │
# │ IMF综合指标（ARA）      │ 加权平均               │ 100%-150%          │
# └────────────────────────┴────────────────────────┴───────────────────┘
#
# ============================================================================
# 三元悖论（Impossible Trinity / Trilemma）
# ============================================================================
#
# 一个国家不能同时实现：
# 1. 货币政策独立性
# 2. 汇率稳定
# 3. 资本自由流动
#
# 只能三选二：
# ┌─────────────────────────────────────────────────────────────────────────┐
# │ 政策组合            │ 牺牲项          │ 典型案例                        │
# ├────────────────────┼────────────────┼────────────────────────────────┤
# │ 固定汇率+资本开放   │ 货币政策独立性 │ 香港货币局                      │
# │ 浮动汇率+资本开放   │ 汇率稳定       │ 美国、英国                      │
# │ 固定汇率+资本管制   │ 资本自由流动   │ 中国（改革开放前）              │
# └────────────────────┴────────────────┴────────────────────────────────┘
#
# 三元悖论指数（Aizenman-Chinn-Ito）：
#   MI + ES + KO ≈ 常数（约为2）
#
#   其中：MI = 货币政策独立性指数（0-1）
#         ES = 汇率稳定性指数（0-1）
