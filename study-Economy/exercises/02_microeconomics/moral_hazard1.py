#
# 道德风险（Moral Hazard）是信息经济学的另一核心概念，与逆向选择不同，它发生在
# 签约之后。道德风险问题最早由保险经济学提出，后被广泛应用于委托-代理理论。
#
# 【道德风险的定义】
# 签约后，一方的行动无法被另一方观测或验证，导致行动选择偏离社会最优。
#
# 【与逆向选择的区别】
# - 逆向选择：事前信息不对称（隐藏信息，Hidden Information）
#   例：投保前健康状况
# - 道德风险：事后信息不对称（隐藏行动，Hidden Action）
#   例：投保后是否谨慎驾驶
#
# ============================================================================
# 委托-代理模型（Principal-Agent Model）
# ============================================================================
#
# 【基本设定】
# - 委托人（Principal）：拥有资产或项目，需要代理人执行
#   例：股东、雇主、保险公司
# - 代理人（Agent）：执行具体行动，拥有行动的私人信息
#   例：经理、员工、投保人
#
# 【模型假设】
# 1. 产出方程：q = e + ε
#    - q: 可观测的产出
#    - e: 代理人努力水平（不可观测）
#    - ε: 随机扰动，ε ~ N(0, σ²)
#
# 2. 代理人效用：U = E[w] - c(e) - (r/2)Var[w]
#    - w: 工资
#    - c(e) = e²/2: 努力成本（凸函数）
#    - r: 绝对风险厌恶系数（r=0为风险中性）
#
# 3. 委托人利润：π = q - w
#
# 4. 线性合同：w = α + β×q
#    - α: 固定工资（底薪）
#    - β: 绩效系数（提成比例，激励强度）
#
# ============================================================================
# 最优合同设计
# ============================================================================
#
# 【代理人最优化问题】
# 给定合同 (α, β)，代理人选择努力水平最大化效用：
#
# max_e E[w] - c(e) - (r/2)Var[w]
# = α + β×e - e²/2 - (r/2)β²σ²
#
# FOC: β - e = 0
# 解得: e* = β（激励相容约束，IC）
#
# 【委托人最优化问题】
# 选择 (α, β) 最大化利润，受约束于：
# - IC: e* = β（代理人最优响应）
# - IR: U(α, β, e*) ≥ U₀（参与约束，代理人愿意签约）
#
# 【风险中性代理人（r=0）】
# 最优合同：β* = 1（全部激励）
# - 代理人承担全部风险，获得全部边际收益
# - 努力达到第一最优水平 e* = 1
# - 固定工资 α 调整以满足参与约束
#
# 【风险厌恶代理人（r>0）】
# 激励与风险的权衡：
# β* = 1 / (1 + r×σ²)
#
# 解读：
# - 风险厌恶越高（r↑）→ β*↓（降低激励强度）
# - 产出波动越大（σ²↑）→ β*↓（降低激励强度）
# - 这导致次优努力水平 e* < 1
#
# ============================================================================
# 效率损失分析
# ============================================================================
#
# 【第一最优（First-Best）】
# - 完全信息：委托人可观测努力
# - 最优努力: e^FB = 1
# - 总剩余: S^FB = e - e²/2 = 1/2
#
# 【第二最优（Second-Best）】
# - 不完全信息：努力不可观测
# - 均衡努力: e^SB = β* < 1
# - 总剩余: S^SB < S^FB
#
# 效率损失 = S^FB - S^SB = (1 - β*)²/2
#
# ============================================================================
# 任务
# ============================================================================
# 1. 分析最优激励合同：计算代理人最优努力和委托人最优β
# 2. 理解风险与激励的权衡：风险厌恶如何影响最优合同
# 3. 计算效率损失：比较第一最优和第二最优
#
# HINT1: 代理人选择努力使边际收益=边际成本：β = c'(e)
# HINT2: 风险厌恶程度影响最优β，公式包含风险溢价
