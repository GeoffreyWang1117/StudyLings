# 理论背景
# ============================================================================
#
# 逆向选择（Adverse Selection）是信息经济学的核心概念之一，由乔治·阿克洛夫
# (George Akerlof) 在1970年的经典论文《柠檬市场》中首次系统阐述，他因此获得
# 2001年诺贝尔经济学奖。
#
# 【信息不对称的类型】
# 信息经济学区分两种主要的信息不对称：
# 1. 事前信息不对称（Hidden Information）→ 逆向选择
#    - 交易前一方拥有另一方不知道的私人信息
#    - 例：二手车卖家知道车况，买家不知道
# 2. 事后信息不对称（Hidden Action）→ 道德风险
#    - 签约后一方的行为无法被另一方观测
#    - 例：购买保险后是否仍然谨慎驾驶
#
# ============================================================================
# 柠檬市场模型（Akerlof's Lemons Model）
# ============================================================================
#
# 【模型设定】
# - 市场上有连续统的卖家，每人有一辆二手车
# - 质量 θ 在 [0, 1] 上均匀分布
# - 卖家知道自己车的质量，买家不知道
# - 卖家保留价格（愿意出售的最低价格）= θ
# - 买家对质量θ的车评价 = v×θ，其中 v > 1（买家比卖家更珍视）
#
# 【关键假设】
# 1. 卖家拥有私人信息（知道θ）
# 2. 买家只知道质量分布，不知道具体质量
# 3. 交易前无法验证质量（事后可以）
# 4. 所有交易者是风险中性的
#
# 【市场均衡分析】
# 给定市场价格 p：
# - 只有保留价格 ≤ p 的卖家愿意卖，即 θ ≤ p 的卖家参与
# - 买家知道这一点，理性预期卖家类型分布
# - 买家的期望价值 = E[v×θ | θ ≤ p] = v × p/2（均匀分布的条件期望）
#
# 均衡条件：买家愿意支付的价格 = 市场价格
#   p = v × p/2
#   解得：p(1 - v/2) = 0
#
# 结论：
# - 若 v < 2，唯一均衡是 p = 0（市场崩溃！）
# - 若 v ≥ 2，可能存在正价格均衡
#
# 【逆向选择机制】
# 1. 价格下降 → 高质量卖家退出
# 2. 平均质量下降 → 买家愿付价格下降
# 3. 恶性循环 → 市场萎缩或崩溃
# 这就是"劣币驱逐良币"的经济学解释
#
# ============================================================================
# 解决逆向选择的机制
# ============================================================================
#
# 【信号传递（Signaling）】- Spence教育信号模型
# - 高质量者通过成本较低的信号与低质量者区分
# - 分离均衡条件：信号成本满足单交叉性质
# - 例：教育作为能力的信号
#
# 【筛选机制（Screening）】
# - 不知情方设计菜单合同诱使类型自我揭示
# - 例：保险公司提供不同免赔额的保单
#
# 【信誉机制（Reputation）】
# - 重复博弈中建立声誉
# - 例：品牌、评价系统
#
# 【第三方认证】
# - 引入可信第三方验证质量
# - 例：二手车检测、审计
#
