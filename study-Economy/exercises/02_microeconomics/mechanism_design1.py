# ============================================================================
# 理论背景
# ============================================================================
#
# 机制设计（Mechanism Design）被称为"反向博弈论"或"逆向博弈论"。
# 博弈论研究给定规则下的均衡，而机制设计研究如何设计规则以实现特定目标。
# Leonid Hurwicz、Eric Maskin 和 Roger Myerson 因此获得2007年诺贝尔经济学奖。
#
# 【核心问题】
# 设计者（政府、拍卖行、平台）不知道参与者的私人信息，
# 如何设计机制（规则）使参与者自愿揭示信息并实现社会目标？
#
# ============================================================================
# 基本概念
# ============================================================================
#
# 【显示原理（Revelation Principle）】
# 任何可以通过某种机制实现的结果，都可以通过一个直接机制实现，
# 在该机制中每个参与者如实报告其类型是均衡策略。
#
# 意义：设计者只需在"直接机制"中寻找最优，无需考虑所有可能的复杂机制。
#
# 【激励相容（Incentive Compatibility, IC）】
# 参与者如实报告私人信息是最优策略。
#
# 形式化：对所有类型 θ 和虚报 θ'
# U(θ, θ) ≥ U(θ, θ')
# 即真实报告的效用不低于任何虚报
#
# 【个人理性（Individual Rationality, IR）】
# 也称参与约束，参与者参与机制的效用不低于不参与。
#
# U(θ, θ) ≥ U₀（外部选项效用）
#
# ============================================================================
# 拍卖理论
# ============================================================================
#
# 拍卖是机制设计最重要的应用之一。William Vickrey (1961) 开创了现代拍卖理论。
#
# 【独立私人价值（IPV）模型】
# - n 个竞拍者，每人有私人估值 vᵢ
# - 估值独立同分布：vᵢ ~ F[v_, v̄]
# - 竞拍者知道自己的估值，不知道他人的估值
# - 出价后决定分配和支付
#
# 【主要拍卖形式】
#
# 1. 英式拍卖（English Auction）
#    - 公开叫价，价格递增
#    - 最后剩下的竞拍者获胜
#    - 支付：第二高估值（近似）
#
# 2. 荷兰式拍卖（Dutch Auction）
#    - 价格从高往低降
#    - 第一个喊停的人获胜
#    - 支付：喊停时的价格
#
# 3. 第一价格密封拍卖（First-Price Sealed-Bid）
#    - 密封出价，最高者获胜
#    - 支付：获胜者的出价
#    - 均衡策略：出价低于真实估值（shading）
#
# 4. 第二价格密封拍卖（Second-Price / Vickrey）
#    - 密封出价，最高者获胜
#    - 支付：第二高的出价
#    - 占优策略：如实出价
#
# 【收入等价定理（Revenue Equivalence Theorem）】
# 在IPV模型中，满足以下条件的任何拍卖机制具有相同的期望收入：
# 1. 物品分配给估值最高者
# 2. 估值为 v_ 的竞拍者期望支付为0
#
# 推论：英式、荷式、第一价格、第二价格拍卖的期望收入相同！
#
# ============================================================================
# VCG机制（Vickrey-Clarke-Groves）
# ============================================================================
#
# VCG机制是一类通用的激励相容机制，可用于多物品拍卖和公共品提供。
#
# 【VCG支付规则】
# 每个参与者支付 = 他给其他人造成的外部性
#
# 对于单物品拍卖：
# - 获胜者支付 = 第二高估值（即Vickrey拍卖）
#
# 对于多物品拍卖：
# - 参与者i的支付 = (没有i时其他人的总效用) - (有i时其他人的总效用)
#
# 【VCG的优良性质】
# 1. 激励相容（IC）：如实报告是占优策略
# 2. 个人理性（IR）：参与不会亏损
# 3. 效率：最大化社会总福利
#
# 【VCG的局限】
# 1. 不保证预算平衡
# 2. 可能被串谋击败
# 3. 计算复杂度可能很高
#
# ============================================================================
# 最优拍卖设计
# ============================================================================
#
# Myerson (1981) 给出了最大化卖家收入的最优拍卖设计。
#
# 【虚拟估值（Virtual Value）】
# ψ(v) = v - (1 - F(v)) / f(v)
#
# 其中F是估值分布函数，f是密度函数。
#
# 【最优保留价】
# 对于均匀分布 v ~ U[0,1]：
# ψ(v) = v - (1-v)/1 = 2v - 1
# 令 ψ(v) = 0，得 v* = 1/2
#
# 卖家应设置保留价 r = 1/2，拒绝低于此价格的出价。
#
# ============================================================================
