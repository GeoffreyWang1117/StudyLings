# 理论背景
# ============================================================================
#
# 实际经济周期（Real Business Cycle, RBC）模型是现代宏观经济学的里程碑，
# 由Finn Kydland和Edward Prescott在1982年提出，他们因此获得2004年诺贝尔经济学奖。
#
# 【RBC革命的意义】
# 1. 方法论革命：基于微观基础的动态一般均衡模型
# 2. 理论革命：经济波动可能是对真实冲击的最优响应
# 3. 校准方法：用微观数据校准模型参数
#
# 【核心观点】
# 经济波动不是市场失灵或政策失误，而是理性经济主体对技术冲击的最优响应。
# 因此，稳定化政策可能是不必要的，甚至是有害的。
#
# ============================================================================
# 模型设定
# ============================================================================
#
# 【代表性家庭】
# 无限期生存，最大化终生效用：
# max E₀ Σ_{t=0}^∞ βᵗ U(Cₜ, 1-Lₜ)
#
# 其中：
# - β ∈ (0,1): 主观折现因子
# - Cₜ: 消费
# - Lₜ: 劳动供给（1-Lₜ为闲暇）
# - 期望 E₀ 对初始信息条件
#
# 【效用函数】
# 常用形式（可加可分）：
# U(C, 1-L) = ln(C) + θ ln(1-L)
#
# 其中 θ > 0 是闲暇的相对权重。
#
# 【生产技术】
# 柯布-道格拉斯生产函数：
# Yₜ = Aₜ Kₜ^α Lₜ^(1-α)
#
# 其中：
# - Aₜ: 全要素生产率（技术水平）
# - Kₜ: 资本存量
# - Lₜ: 劳动投入
# - α ∈ (0,1): 资本份额
#
# 【技术冲击过程】
# AR(1)过程：
# ln(Aₜ) = ρ ln(Aₜ₋₁) + εₜ，εₜ ~ N(0, σ²)
#
# 其中 ρ ∈ (0,1) 是持续性参数。
#
# 【资源约束】
# Yₜ = Cₜ + Iₜ（产出 = 消费 + 投资）
#
# 【资本演化】
# Kₜ₊₁ = (1-δ)Kₜ + Iₜ
#
# 其中 δ ∈ (0,1) 是折旧率。
#
# ============================================================================
# 竞争均衡条件
# ============================================================================
#
# 【家庭最优化】
# 1. 欧拉方程（跨期消费选择）：
#    Uᶜ(t) = β E_t [(1 + rₜ₊₁) Uᶜ(t+1)]
#
#    对数效用：1/Cₜ = β E_t [(1 + rₜ₊₁)/Cₜ₊₁]
#
# 2. 劳动-闲暇权衡：
#    Uₗ(t) / Uᶜ(t) = wₜ
#
#    对数效用：θ/(1-Lₜ) × Cₜ = wₜ
#
# 【企业最优化】
# 竞争性企业利润最大化得：
# - 工资 = 劳动边际产出：wₜ = (1-α) Yₜ/Lₜ
# - 资本租金 = 资本边际产出：rₜ = α Yₜ/Kₜ - δ
#
# ============================================================================
# 稳态分析
# ============================================================================
#
# 稳态是指没有冲击时经济的长期均衡状态，所有变量保持不变。
#
# 【稳态条件】
# 欧拉方程稳态：
# 1 = β(1 + r)
# r = 1/β - 1
#
# 资本边际产出：
# r + δ = α Y/K
# K/Y = αβ / (1 - β(1-δ))
#
# 【稳态比率】
# - 资本产出比：K/Y = αβ / (1 - β(1-δ))
# - 投资产出比：I/Y = δ K/Y
# - 消费产出比：C/Y = 1 - I/Y
#
# ============================================================================
# 任务
# ============================================================================
# 1. 理解RBC模型结构：熟悉模型设定和均衡条件
# 2. 计算稳态：求解稳态下的主要比率
# 3. 分析技术冲击的影响：理解冲击传导机制
#
# HINT1: 在稳态，所有变量增长率为0，技术水平标准化为1
# HINT2: 欧拉方程连接跨期决策，是动态模型的核心
# HINT3: 资本产出比由折现因子和折旧率决定

