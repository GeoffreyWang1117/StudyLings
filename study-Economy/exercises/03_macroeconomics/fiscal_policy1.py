# 理论背景
# ============================================================================
#
# 财政政策（Fiscal Policy）是政府通过支出和税收调控经济的手段，
# 与货币政策并列为宏观经济稳定化的两大工具。
#
# 【财政政策工具】
# 1. 政府支出（G）：政府购买商品和服务
# 2. 转移支付（TR）：社会保障、失业救济等
# 3. 税收（T）：个人所得税、企业税、消费税等
#
# 【财政政策类型】
# 1. 扩张性财政政策：增加支出或减税 → 刺激经济
# 2. 紧缩性财政政策：减少支出或加税 → 抑制过热
# 3. 自动稳定器：税收和转移支付随经济周期自动调整
#
# ============================================================================
# 政府预算约束
# ============================================================================
#
# 【单期预算约束】
# Gₜ + iₜ Bₜ₋₁ = Tₜ + ΔBₜ
#
# 其中：
# - Gₜ: 政府支出（不含利息）
# - iₜ Bₜ₋₁: 债务利息支付
# - Tₜ: 税收收入
# - ΔBₜ = Bₜ - Bₜ₋₁: 新增债务
#
# 整理：
# Bₜ = Gₜ + (1+iₜ)Bₜ₋₁ - Tₜ
#
# 【财政赤字定义】
# 总赤字 = G + iB - T
# 初级赤字 = G - T（不含利息支付）
#
# 【跨期预算约束】
# 政府不能永远借钱，长期必须满足：
# Bₜ₋₁ = Σₛ₌₀^∞ (Tₜ₊ₛ - Gₜ₊ₛ) / (1+r)ˢ
#
# 即：现有债务 = 未来初级盈余的现值
#
# ============================================================================
# 李嘉图等价（Ricardian Equivalence）
# ============================================================================
#
# 【理论内容】
# 在特定条件下，政府融资方式（债务vs当期税收）不影响消费和总需求。
#
# 直觉：今天减税意味着未来加税（政府预算约束）
# 理性消费者预期到未来税负，不会改变消费
#
# 【李嘉图等价条件】
# 1. 消费者理性且有远见
# 2. 资本市场完善（政府和私人借贷利率相同）
# 3. 无扭曲性税收
# 4. 跨代利他（Barro 1974）
#
# 【等价失效的原因】
# 1. 流动性约束：部分消费者无法借贷
# 2. 有限寿命：不关心死后的税负
# 3. 扭曲性税收：税收影响激励
# 4. 不确定性：对未来税收的预期有误
#
# ============================================================================
# 财政乘数
# ============================================================================
#
# 【政府支出乘数】
# k_G = ΔY / ΔG
#
# 简单凯恩斯模型：k_G = 1 / (1 - MPC)
# 考虑税收反馈：k_G = 1 / (1 - MPC(1-t))
#
# 【税收乘数】
# k_T = ΔY / ΔT = -MPC / (1 - MPC)
#
# 税收乘数的绝对值 < 支出乘数
#
# 【平衡预算乘数】
# ΔG = ΔT 时：k_BB = 1
# 即使预算平衡，政府支出仍有扩张效应
#
# 【乘数的现实考量】
# 1. 货币政策反应：央行可能加息抵消财政扩张
# 2. 挤出效应：政府借贷推高利率，挤出私人投资
# 3. 开放经济：部分需求"漏出"到进口
# 4. 预期效应：理性预期可能削弱乘数
#
# ============================================================================
# 债务可持续性
# ============================================================================
#
# 【债务/GDP比的动态】
# bₜ = [(1+r)/(1+g)] × bₜ₋₁ - pbₜ
#
# 其中：
# - b = B/Y: 债务/GDP比
# - pb = (T-G)/Y: 初级盈余/GDP比
# - r: 实际利率
# - g: 实际GDP增长率
#
# 【稳定债务比所需的初级盈余】
# 令 bₜ = bₜ₋₁ = b：
# pb* = [(r-g)/(1+g)] × b
#
# 如果 r > g，需要初级盈余才能稳定债务比
# 如果 r < g，可以有初级赤字而债务比仍稳定
#
# 【债务可持续性条件】
# 长期来看，政府必须能够支付债务利息
# 否则面临债务违约或恶性通胀风险
