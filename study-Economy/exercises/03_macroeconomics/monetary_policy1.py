# 实现价格稳定和经济增长等目标。
#
# 【货币政策的目标】
# 1. 价格稳定（主要目标）：保持低且稳定的通货膨胀
# 2. 充分就业：使失业率接近自然失业率
# 3. 经济增长：促进可持续的经济增长
# 4. 金融稳定：维护金融体系的稳定
#
# 【央行独立性】
# 现代央行通常具有政治独立性，以避免政府的短期利益影响货币政策。
# - 工具独立性：央行自主决定政策工具
# - 目标独立性：央行自主设定政策目标
#
# ============================================================================
# 货币政策工具
# ============================================================================
#
# 【常规工具】
#
# 1. 政策利率（Policy Rate）
#    - 美国：联邦基金利率（Federal Funds Rate）
#    - 欧洲：主要再融资利率（Main Refinancing Rate）
#    - 中国：中期借贷便利（MLF）利率、贷款市场报价利率（LPR）
#
# 2. 公开市场操作（Open Market Operations）
#    央行买卖政府债券以调节货币供给
#    - 买入债券 → 货币供给↑ → 利率↓
#    - 卖出债券 → 货币供给↓ → 利率↑
#
# 3. 准备金要求（Reserve Requirements）
#    商业银行必须持有的准备金比例
#    - 降低准备金率 → 可贷资金↑ → 货币供给↑
#
# 4. 贴现窗口（Discount Window）
#    央行向商业银行提供的紧急贷款
#
# 【非常规工具】（零利率下限约束时使用）
#
# 1. 量化宽松（Quantitative Easing, QE）
#    大规模购买长期资产（国债、MBS等）
#
# 2. 前瞻指引（Forward Guidance）
#    央行对未来政策路径的承诺
#
# 3. 负利率政策（Negative Interest Rates）
#    对银行准备金收取费用
#
# 4. 收益率曲线控制（Yield Curve Control）
#    直接控制特定期限的债券收益率
#
# ============================================================================
# 货币政策传导机制
# ============================================================================
#
# 【利率渠道】
# 央行降息 → 贷款利率↓ → 投资↑消费↑ → 总需求↑ → 产出↑
#
# i↓ → r↓ → I↑, C↑ → Y↑
#
# 【资产价格渠道】
# 央行降息 → 股价↑房价↑ → 财富效应 → 消费↑
#
# i↓ → 资产价格↑ → 财富↑ → C↑
#
# 【汇率渠道】
# 央行降息 → 本币贬值 → 出口↑进口↓ → 净出口↑
#
# i↓ → E↓ → NX↑ → Y↑
#
# 【信贷渠道】
# - 银行贷款渠道：央行政策影响银行贷款意愿和能力
# - 资产负债表渠道：利率影响借款人的净值和信用状况
#
# 【预期渠道】
# 央行沟通影响私人部门对未来经济和政策的预期
#
# ============================================================================
# 泰勒规则
# ============================================================================
#
# John Taylor (1993) 提出的货币政策规则：
#
# i = r* + π + 0.5(π - π*) + 0.5(y - y*)
#
# 其中：
# - i: 名义利率
# - r*: 均衡实际利率（约2%）
# - π: 当前通胀率
# - π*: 通胀目标（约2%）
# - y - y*: 产出缺口
#
# 【泰勒原则】
# 通胀系数 > 1，即通胀上升1%时，名义利率上升超过1%。
# 这确保实际利率上升，从而抑制需求，稳定通胀。
#
# 【泰勒规则的变体】
# 1. 前瞻性规则：使用预期通胀和产出缺口
# 2. 惯性规则：加入利率平滑项
# 3. 最优控制规则：从央行损失函数推导
#
