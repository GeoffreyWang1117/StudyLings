# 理论背景
# ============================================================================
#
# 新凯恩斯（New Keynesian, NK）模型是当代货币政策分析的主流框架。
# 它在RBC模型的微观基础上加入名义刚性，使货币政策具有实际效果。
#
# 【新凯恩斯革命】
# 1. 保留RBC的微观基础和理性预期
# 2. 加入垄断竞争和名义刚性
# 3. 货币政策有实际效果（非货币中性）
# 4. 为央行稳定化政策提供理论基础
#
# 【与RBC的关键区别】
# - RBC：完全竞争 + 灵活价格 → 货币中性
# - NK：垄断竞争 + 粘性价格 → 货币政策有效
#
# ============================================================================
# 模型设定
# ============================================================================
#
# 【垄断竞争】
# 每个企业生产差异化产品，有一定市场力量。
# 需求曲线：Yᵢ = (Pᵢ/P)^(-ε) Y
# 其中 ε > 1 是需求弹性。
#
# 【Calvo定价】
# 每期有 (1-θ) 的企业可以重新定价，θ 的企业保持价格不变。
# θ 越大，价格粘性越强。
# 平均价格持续期 = 1/(1-θ)
#
# ============================================================================
# 三方程新凯恩斯模型
# ============================================================================
#
# 【1. 新凯恩斯菲利普斯曲线（NKPC）】
# πₜ = β E_t[πₜ₊₁] + κ xₜ
#
# 其中：
# - πₜ: 通胀率
# - xₜ: 产出缺口（实际产出与潜在产出之差）
# - κ: 菲利普斯曲线斜率（与价格粘性负相关）
# - β: 折现因子
#
# 经济含义：
# - 当前通胀取决于预期未来通胀和当前产出缺口
# - 与传统菲利普斯曲线的区别：前瞻性（forward-looking）
#
# 【2. 动态IS曲线】
# xₜ = E_t[xₜ₊₁] - σ(iₜ - E_t[πₜ₊₁] - rⁿ)
#
# 其中：
# - iₜ: 名义利率
# - rⁿ: 自然利率（灵活价格下的均衡利率）
# - σ: 跨期替代弹性的倒数
#
# 经济含义：
# - 来自家庭欧拉方程的对数线性化
# - 实际利率高于自然利率 → 产出缺口下降
#
# 【3. 货币政策规则（泰勒规则）】
# iₜ = rⁿ + φ_π πₜ + φ_x xₜ + εₜⁱ
#
# 其中：
# - φ_π > 1: 对通胀的反应系数（泰勒原则）
# - φ_x ≥ 0: 对产出缺口的反应系数
# - εₜⁱ: 货币政策冲击
#
# ============================================================================
# 关键参数关系
# ============================================================================
#
# 【κ 与 Calvo参数的关系】
# κ = (1-θ)(1-βθ)/θ × λ
#
# 其中 λ 取决于效用函数和生产函数的参数。
#
# 简化形式：κ ≈ (1-θ)(1-βθ)/θ
#
# 【平均价格持续期】
# E[持续期] = 1/(1-θ)
#
# 例：θ = 0.75 → 平均持续期 = 4个季度 = 1年
#
# ============================================================================
# 泰勒原则
# ============================================================================
#
# φ_π > 1 是确定性均衡的必要条件。
#
# 直觉：通胀上升1%时，名义利率上升超过1%，
# 从而实际利率上升，抑制需求，稳定通胀。
#
# 如果 φ_π < 1，正反馈循环导致不稳定。
#
# ============================================================================
# 神圣巧合（Divine Coincidence）
# ============================================================================
#
# 在基准NK模型中，稳定通胀同时稳定产出缺口。
#
# 从NKPC：πₜ = β E_t[πₜ₊₁] + κ xₜ
# 如果能保持 πₜ = 0，则 xₜ = 0。
#
# 意义：央行只需要一个目标（通胀）
#
# 但现实中存在成本推动冲击，需要在通胀和产出之间权衡。
#
