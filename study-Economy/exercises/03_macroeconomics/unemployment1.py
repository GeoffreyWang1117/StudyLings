# -----------------------------------------------------------------------------
# 一、失业的分类
# -----------------------------------------------------------------------------
#
# 1. 摩擦性失业（Frictional Unemployment）
#    - 定义：劳动者在转换工作过程中的暂时性失业
#    - 原因：信息不完全、搜寻需要时间
#    - 特征：短期、自愿、不可避免
#    - 例如：刚毕业的学生找工作、跳槽期间的间隙
#
# 2. 结构性失业（Structural Unemployment）
#    - 定义：劳动者技能与市场需求不匹配导致的失业
#    - 原因：技术变革、产业转移、区域差异
#    - 特征：长期、需要再培训
#    - 例如：制造业工人因自动化失业、煤炭产业衰退
#
# 3. 周期性失业（Cyclical Unemployment）
#    - 定义：经济周期波动导致的失业
#    - 原因：总需求不足、经济衰退
#    - 特征：与GDP增长负相关，可通过宏观政策调节
#    - 例如：2008年金融危机后的大规模失业
#
# 4. 季节性失业（Seasonal Unemployment）
#    - 定义：季节性因素导致的失业
#    - 例如：农业淡季、旅游淡季
#
# -----------------------------------------------------------------------------
# 二、自然失业率（NAIRU）
# -----------------------------------------------------------------------------
#
# 定义：不加速通胀的失业率（Non-Accelerating Inflation Rate of Unemployment）
#
# u* = 摩擦性失业率 + 结构性失业率
#
# 特征：
# - 是长期均衡失业率
# - 不为零（总有搜寻摩擦）
# - 会随时间变化（劳动力市场结构变化）
#
# 与菲利普斯曲线的关系：
# - 当 u < u*：通胀加速
# - 当 u > u*：通胀减速
# - 当 u = u*：通胀稳定
#
# -----------------------------------------------------------------------------
# 三、搜寻匹配模型（DMP模型）
# -----------------------------------------------------------------------------
#
# Diamond-Mortensen-Pissarides模型是理解劳动力市场摩擦的核心框架。
# 三位经济学家因此获得2010年诺贝尔经济学奖。
#
# 核心思想：
# - 劳动力市场是"搜寻市场"而非瓦尔拉斯市场
# - 匹配需要时间和成本
# - 失业和职位空缺可以同时存在
#
# 1. 匹配函数（Matching Function）
#
#    M(U, V) = A × U^α × V^(1-α)
#
#    其中：
#    - M：每期新匹配数
#    - U：失业人数
#    - V：职位空缺数
#    - A：匹配效率（反映劳动力市场效率）
#    - α：失业者在匹配中的弹性（通常约0.5）
#
#    匹配函数性质：
#    - 规模报酬不变：M(λU, λV) = λM(U, V)
#    - 关于U和V递增
#    - 关于U和V边际递减
#
# 2. 劳动力市场紧张程度（Market Tightness）
#
#    θ = V / U
#
#    - θ高：市场对劳动者有利（空缺多，失业少）
#    - θ低：市场对企业有利（空缺少，失业多）
#
# 3. 工作发现率（Job Finding Rate）
#
#    f = M(U, V) / U = A × θ^(1-α)
#
#    - f是θ的增函数
#    - 市场越紧张，失业者越容易找到工作
#
# 4. 职位填充率（Vacancy Filling Rate）
#
#    q = M(U, V) / V = A × θ^(-α)
#
#    - q是θ的减函数
#    - 市场越紧张，企业越难填补空缺
#
# 5. 稳态失业率
#
#    劳动力市场流量均衡条件：
#    流入失业池 = 流出失业池
#    s × (1-u) = f × u
#
#    求解得稳态失业率：
#    u* = s / (s + f)
#
#    其中：
#    - s：分离率（每期在职者失业的概率）
#    - f：工作发现率
#
# -----------------------------------------------------------------------------
# 四、贝弗里奇曲线（Beveridge Curve）
# -----------------------------------------------------------------------------
#
# 描述失业率(u)与职位空缺率(v)之间的负相关关系。
#
# 数学推导：
# 稳态条件：s(1-u) = f(θ)×u
# 由 θ = v/u 和 f(θ) = Aθ^(1-α)：
#
# s(1-u) = A(v/u)^(1-α) × u = Au^α × v^(1-α)
#
# 这隐含了u和v的负相关关系。
#
# 曲线移动：
# - 内移：匹配效率A提高（更高效的劳动力市场）
# - 外移：匹配效率A下降（结构性失业增加）
#
# 政策含义：
# - 曲线上移动：周期性因素（总需求变化）
# - 曲线本身移动：结构性因素（需要结构性改革）
#
# -----------------------------------------------------------------------------
# 五、效率工资理论（Efficiency Wage Theory）
# -----------------------------------------------------------------------------
#
# 解释为什么企业可能支付高于市场出清水平的工资，导致非自愿失业。
#
# 1. 索洛模型（Solow, 1979）
#
#    假设：工人努力程度e是工资w的函数，e = e(w)，e' > 0
#
#    企业目标：max π = F(e(w)L) - wL
#
#    对w求导：
#    F'(eL) × e'(w) × L - L = 0
#    F'(eL) × e'(w) = 1
#
#    对L求导（劳动需求条件）：
#    F'(eL) × e(w) = w
#
#    两式相除得索洛条件：
#    e'(w) × w / e(w) = 1
#
#    即：努力对工资的弹性 = 1
#
# 2. 效率工资的其他解释
#
#    a) 避免偷懒模型（Shapiro-Stiglitz, 1984）
#       - 高工资提高偷懒被发现后的损失
#       - 工人为保住高薪工作而努力
#
#    b) 劳动力流动模型
#       - 高工资降低离职率
#       - 减少招聘和培训成本
#
#    c) 公平工资模型（Akerlof-Yellen）
#       - 工人根据"公平"工资决定努力程度
#       - 低于公平工资导致消极怠工
#
#    d) 逆向选择模型
#       - 高工资吸引高能力工人
#       - 工资是能力的信号
#
# 3. 效率工资与失业
#
#    - 效率工资 > 市场出清工资
#    - 劳动供给 > 劳动需求
#    - 产生非自愿失业
#
# -----------------------------------------------------------------------------
# 六、失业政策分析
# -----------------------------------------------------------------------------
#
# 1. 降低摩擦性失业
#    - 改善职业信息服务
#    - 发展职业中介
