# 【主要增长模型】
#
# 1. 哈罗德-多马模型（Harrod-Domar, 1940s）
#    - 核心思想：储蓄率决定增长率
#    - 公式：g = s/v（增长率 = 储蓄率/资本产出比）
#    - 政策含义：增加储蓄（或外援）可提高增长
#    - 局限：忽略技术进步，假设固定系数生产函数
#    - 发展中国家应用：世界银行早期用此模型计算"融资缺口"
#
# 2. 索洛模型（Solow, 1956）
#    - 核心思想：资本边际报酬递减导致稳态
#    - 生产函数：Y = A × K^α × L^(1-α)（Cobb-Douglas）
#    - 稳态条件：储蓄 = 折旧 + 人口增长 + 技术进步消耗的资本
#    - 关键结论：长期增长完全由技术进步决定
#    - 收敛假说：穷国应比富国增长更快
#
# 3. 内生增长模型
#    a) AK模型（Rebelo, 1991）
#       - 资本边际报酬恒定，没有稳态
#       - g = sA - δ
#       - 政策可以永久影响增长率
#
#    b) 人力资本模型（Lucas, 1988; Mankiw-Romer-Weil, 1992）
#       - 人力资本积累是增长源泉
#       - 教育投资有外部性
#
#    c) R&D模型（Romer, 1990）
#       - 知识积累驱动增长
#       - 创新的正外部性
#
# 【增长核算（Growth Accounting）】
# 分解增长来源：
# gY = gA + α×gK + (1-α)×gL
# 其中gA称为"索洛残差"或全要素生产率（TFP）增长
#
# 【发展核算（Development Accounting）】
# 分解收入差距来源：
# 收入差距 = 物质资本差异 + 人力资本差异 + TFP差异
# Hall & Jones (1999)发现：TFP差异解释了约60%的收入差距
#
# 【收敛假说】
# - 绝对收敛：所有穷国增长更快（数据不支持）
# - 条件收敛：控制结构因素后，穷国收敛向自己的稳态
# - 收敛俱乐部：只有相似国家之间收敛
