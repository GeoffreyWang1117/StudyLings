# 越来越多的证据表明，制度是解释国家间发展差距的根本原因。
#
# 【什么是制度？】
# Douglas North定义：制度是社会中的游戏规则，是人为设计的约束，
# 塑造人类互动的激励结构。
#
# 制度包括：
# 1. 正式制度：法律、宪法、产权规则
# 2. 非正式制度：习俗、传统、社会规范
# 3. 执行机制：使规则有效的力量
#
# 【制度类型】
#
# 1. 经济制度
#    - 产权保护：投资和创新的基础
#    - 合同执行：支持复杂交易
#    - 市场准入：竞争与效率
#    - 监管环境：营商便利度
#
# 2. 政治制度
#    - 民主与问责
#    - 法治（Rule of Law）
#    - 权力制衡
#    - 政治稳定性
#
# 3. 社会制度
#    - 信任与社会资本
#    - 文化规范
#    - 宗教影响
#
# 【为什么制度重要？】
#
# 1. 降低交易成本
#    - Coase定理：交易成本决定资源配置效率
#    - 好的制度减少信息不对称、欺诈风险
#
# 2. 保护产权
#    - 产权安全是投资的前提
#    - 征用风险抑制长期投资
#
# 3. 提供正确激励
#    - 创新回报 vs 寻租回报
#    - 生产性活动 vs 掠夺性活动
#
# 【Acemoglu-Robinson框架】
# 《国家为何失败》（Why Nations Fail, 2012）
#
# 核心概念：
# 1. 包容性制度（Inclusive Institutions）
#    - 经济：广泛产权保护、市场准入
#    - 政治：多元化、权力分散、法治
#    - 结果：创新、竞争、持续增长
#
# 2. 汲取性制度（Extractive Institutions）
#    - 经济：少数人控制资源、限制竞争
#    - 政治：权力集中、缺乏制衡
#    - 结果：可能有短期增长，但不可持续
#
# 关键时刻（Critical Juncture）：
# - 制度变迁的窗口期
# - 例：黑死病、工业革命、殖民化
#
# 【制度的起源】
#
# 1. 地理假说（Diamond, 1997）
#    - 气候、作物、疾病环境
#    - 批评：地理恒定，但增长路径可变
#
# 2. 殖民历史假说（Acemoglu et al., 2001）
#    - 定居者殖民地 vs 掠夺性殖民地
#    - 制度的历史持久性
#
# 3. 文化假说（Weber, Landes）
#    - 价值观、工作伦理
#    - 争议较大
#
# 【发展中国家的制度挑战】
# 1. 殖民遗产：边界、法律体系、汲取性制度
# 2. 种族多样性：可能增加协调成本
# 3. 资源诅咒：资源富国的制度陷阱
# 4. 贫困陷阱：低收入限制制度投资
#
