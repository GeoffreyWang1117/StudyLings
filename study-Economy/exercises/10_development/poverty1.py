# 3. 贫困具有代际传递性
# 4. 季节性贫困（农闲期间更严重）
# 5. 脆弱性高：容易因冲击陷入贫困
#
# 【FGT贫困指数族】
# Foster-Greer-Thorbecke (1984) 提出的贫困测量指标：
#
# P_α = (1/n) × Σ ((z - yᵢ)/z)^α × I(yᵢ < z)
#
# 其中：
# - n: 总人口
# - z: 贫困线
# - yᵢ: 第i个人的收入
# - I(): 指示函数，当yᵢ < z时为1
# - α: 贫困厌恶参数
#
# α的不同取值：
# - α = 0: 贫困发生率（Headcount Ratio）
# - α = 1: 贫困差距指数（Poverty Gap）
# - α = 2: 贫困严重程度（Poverty Severity/Squared Poverty Gap）
#
# 【FGT指数的性质】
# 1. 单调性：收入下降 → P增加（α > 0时满足）
# 2. 转移敏感性：穷人之间从更穷转向较不穷的人会增加P（α > 1时满足）
# 3. 可分解性：可以按子群分解
#
# 【贫困与增长的关系】
# - 增长弹性：经济增长对贫困的影响程度
# - 益贫增长：使穷人受益更多的增长模式
# - Kuznets曲线：发展初期不平等上升，后期下降
