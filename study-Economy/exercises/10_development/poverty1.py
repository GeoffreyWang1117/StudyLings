#    - 绝对贫困：收入低于维持基本生存所需（固定标准）
#    - 相对贫困：收入低于社会中位数的一定比例（随社会发展变化）
#
# 2. 多维贫困（Alkire-Foster方法）
#    贫困不仅是收入不足，还包括：
