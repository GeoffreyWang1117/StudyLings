# 说明：
# 心理账户（Mental Accounting）是Richard Thaler提出的概念，
# 描述人们在心理上将财富划分为不同账户分别管理的倾向。
# 这与标准经济学的货币可替代性假设形成对比。
#
# 【理论背景】
#
# Thaler (1980, 1985, 1999) 系统发展了心理账户理论。
# 2017年，Thaler因行为经济学的贡献获得诺贝尔经济学奖。
#
# 核心洞见：
# - 人们不把钱看作完全可替代的
# - 不同来源和用途的钱被区别对待
# - 心理账户影响消费和投资决策
#
# 【与传统经济学的区别】
#
# 传统经济学假设"货币可替代性"（Fungibility）：
# - 一元钱就是一元钱，无论来源或用途
# - 边际消费倾向不应该因收入来源而异
# - 消费决策应该基于总财富
#
# 行为经济学发现：
# - 人们对不同来源的钱有不同的消费倾向
# - 心理账户之间存在"隔墙"
# - 这导致非理性的财务决策
#
# 【心理账户的三个层面】
#
# 1. 感知与编码（Perception & Coding）
#    - 如何感知和评价交易结果
#    - 整合vs分离的偏好
#    - 快乐编辑（Hedonic Editing）
#
# 2. 账户分配（Account Assignment）
#    - 将消费和收入分配到不同账户
#    - 账户标签（用途限定）
#    - 预算约束的心理设定
#
# 3. 账户结算（Account Evaluation）
#    - 定期结算盈亏
#    - 何时"关闭"账户
#    - 沉没成本效应
#
# 【核心概念】
#
# 1. 账户分离（Account Segregation）
#    - 将财富分入不同的心理账户
#    - 如：日常支出、娱乐、储蓄
#    - 账户之间不可随意转移
#
# 2. 账户标签（Mental Labels）
#    - 钱有特定的"用途标签"
#    - 工资用于日常，奖金用于享乐
#    - 标签影响消费模式
#
# 3. 违反可替代性
#    - 同样金额因来源不同被不同对待
#    - 意外之财更容易被挥霍
#    - 劳动所得更谨慎使用
#
# 【快乐编辑原则】
# Thaler (1985) 提出的最优化心理体验的策略：
#
# 1. 分离收益（Segregate gains）
#    - 多个好消息分开报告
#    - v(x) + v(y) > v(x+y) for x,y > 0
#
# 2. 整合损失（Integrate losses）
#    - 多个坏消息合并报告
#    - v(-x-y) > v(-x) + v(-y)
#
# 3. 小损失与大收益整合（Integration）
#    - "银线效应"：小坏消息与大好消息一起
#    - v(x-y) > v(x) + v(-y) for x > y > 0
#
# 4. 小收益与大损失分离（Segregation）
#    - "安慰奖效应"
#    - v(-x) + v(y) > v(-x+y) for x > y > 0
#
# 【主要行为现象】
#
# 1. 边际消费倾向差异
#    - 意外之财：高MPC（容易花掉）
#    - 劳动收入：低MPC（谨慎消费）
#    - 财富增值：最低MPC（不动用）
#
# 2. 沉没成本效应
#    - 考虑已经花费的不可回收成本
#    - 继续投入以避免"关闭亏损账户"
#
# 3. 支付解耦
#    - 预付使消费更愉快（无支付痛苦）
#    - 信用卡使支付痛苦减少
#
# 4. 赌资效应（House Money Effect）
#    - 赢钱后更愿意冒险
#    - 用"赌场的钱"赌
#
# 5. 回本效应（Break-even Effect）
#    - 亏损后冒更大风险试图回本
#    - 不愿关闭亏损账户
#
# 【应用领域】
#
# 1. 个人理财
#    - 预算分类
#    - 储蓄账户设计
#    - 债务管理
#
# 2. 营销策略
