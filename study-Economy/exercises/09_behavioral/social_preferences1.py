# 说明：
# 社会偏好（Social Preferences）指人们不仅关心自己的物质收益，
# 也关心他人的收益以及分配的公平性。这与传统经济学的自利假设形成对比。
#
# 【理论背景】
#
# 传统经济学假设"经济人"（Homo Economicus）：
# - 完全自利，只关心自己的收益
# - 理性最大化自身效用
# - 在博弈中选择纳什均衡策略
#
# 然而，大量实验证据表明人们表现出社会偏好：
# - 独裁者博弈中给予他人正的份额
# - 最后通牒博弈中拒绝不公平提议
# - 公共品博弈中贡献正的金额
# - 信任博弈中展现信任与互惠
#
# 【与传统经济学的核心区别】
#
# 1. 效用函数的扩展
#    - 传统：Uᵢ = f(xᵢ)（只关心自己的收益）
#    - 社会偏好：Uᵢ = f(xᵢ, xⱼ, ...)（关心自己和他人的收益）
#
# 2. 对纳什均衡的挑战
#    - 标准理论预测：独裁者给予0，最后通牒提议接近0
#    - 实际观察：显著的给予和公平分配
#
# 3. 合作的可能性
#    - 传统理论难以解释一次性博弈中的合作
#    - 社会偏好提供了解释机制
#
# 【主要社会偏好类型】
#
# 1. 利他主义（Altruism）
#    - 纯粹关心他人福利
#    - Uᵢ = xᵢ + γxⱼ，其中 γ > 0
#    - 无条件的善意
#
# 2. 不平等厌恶（Inequality Aversion）
#    - Fehr-Schmidt模型 (1999)
#    - 厌恶有利和不利的不平等
#    - Uᵢ = xᵢ - α×max(xⱼ-xᵢ,0) - β×max(xᵢ-xⱼ,0)
#
# 3. 互惠（Reciprocity）
#    - 回报善意，惩罚恶意
#    - 意图和动机很重要
#    - 正互惠 + 负互惠
#
# 4. 公平偏好（Fairness）
#    - 关心结果的公平分配
#    - 可能接受较低收益以实现公平
#
# 【核心模型：Fehr-Schmidt不平等厌恶】
#
# Uᵢ = xᵢ - α×max(xⱼ-xᵢ,0) - β×max(xᵢ-xⱼ,0)
#
# 其中：
# - xᵢ：自己的收益
# - xⱼ：他人的收益
# - α：劣势不平等厌恶（被占便宜的痛苦）
# - β：优势不平等厌恶（占便宜的内疚）
#
# 参数约束：
# - α ≥ β（人们对被占便宜更敏感）
# - 0 ≤ β < 1（否则会一直送钱）
# - α ≥ 0
#
# 【经典实验范式】
#
# 1. 独裁者博弈（Dictator Game）
#    - 独裁者决定如何分配一笔钱
#    - 接收者被动接受
#    - 标准预测：给予0；实际：平均给予20-30%
#
# 2. 最后通牒博弈（Ultimatum Game）
#    - 提议者提出分配方案
#    - 回应者决定接受或拒绝（拒绝则双方都得0）
#    - 标准预测：提议最小单位；实际：平均提议40-50%
#
# 3. 公共品博弈（Public Goods Game）
#    - 每人决定贡献多少到公共池
#    - 公共池乘以系数后平均分配
#    - 标准预测：贡献0；实际：初始贡献约50%
#
# 4. 信任博弈（Trust Game）
#    - 投资者决定发送多少给受托人
#    - 发送额乘以3（社会收益）
#    - 受托人决定返还多少
#    - 测量信任和互惠
#
# 【跨文化证据】
#
# Henrich et al. (2001) 在15个小规模社会的研究：
# - 所有社会都展现出社会偏好
# - 但程度和形式存在显著差异
# - 市场整合程度与合作行为正相关
