# TOPIC: 时间偏好与双曲贴现
#
# 说明：
# 时间偏好（Time Preference）描述人们如何在不同时间点的收益之间做选择。
# 行为经济学发现，人们的实际贴现行为与传统指数贴现模型存在系统性偏差。
#
# 【理论背景】
#
# 传统经济学假设人们使用指数贴现（Exponential Discounting）：
# - 由Samuelson (1937) 提出的贴现效用模型（DU模型）
# - 假设贴现率在各时期保持恒定
# - 满足时间一致性（Time Consistency）
#
# 然而，大量实验证据表明人们表现出：
# - 现在偏好（Present Bias）：对即时收益的过度偏好
# - 时间不一致性（Time Inconsistency）：计划与实际行为不符
# - 偏好反转（Preference Reversal）：随时间推移改变选择
#
# 【与传统经济学的区别】
#
# 1. 指数贴现（标准模型）
#    - 贴现因子：D(t) = δ^t，其中 0 < δ < 1
#    - 特点：贴现率恒定 r = -ln(δ)
#    - 时间一致：今天对"明天vs后天"的偏好 = 明天对"明天vs后天"的偏好
#    - 理性人模型：能够完美执行长期计划
#
# 2. 双曲贴现（行为模型）
#    - 贴现因子：D(t) = 1/(1 + kt)，其中 k > 0
#    - 特点：近期贴现率高，远期贴现率低
#    - 时间不一致：偏好会随时间改变
#    - 解释拖延、过度消费等"非理性"行为
#
# 3. 准双曲贴现（β-δ模型，Laibson 1997）
#    - D(0) = 1
#    - D(t) = βδ^t for t > 0
#    - β < 1 捕捉"现在偏好"
#    - 简化的数学形式，便于分析
#
# 【核心概念】
#
# 现在偏好（Present Bias）：
# - 对当下收益给予不成比例的高权重
# - β < 1 表示现在偏好的程度
# - β = 1 退化为标准指数贴现
#
# 时间不一致性（Time Inconsistency）：
# - 之前的计划与当下的选择不符
# - 典型表现：计划明天开始节食，但明天又推迟
# - 源于近期贴现率高于远期贴现率
#
# 【自我认知类型】
#
# 1. 天真者（Naifs）：
#    - 不预期自己未来会有自控问题
#    - 认为自己未来会按计划行事
#    - 容易受到诱惑，反复拖延
#
# 2. 成熟者（Sophisticates）：
#    - 正确预期自己未来的自控问题
#    - 可能使用承诺设备（Commitment Devices）
#    - 但也可能因预期失控而提前放纵
#
# 3. 部分天真者（Partial Naifs）：
#    - 认识到自控问题但低估其程度
#    - 最常见的类型
#
# 【行为后果】
#
# 1. 拖延（Procrastination）
#    - 即时成本被放大，延迟收益被贬低
#    - "明天再做"的无限循环
#
# 2. 过度消费（Overconsumption）
#    - 即时消费的吸引力过大
#    - 储蓄不足，负债过多
#
# 3. 成瘾行为（Addiction）
#    - 即时愉悦 vs 长期健康
#    - 戒断困难
#
# 4. 健康决策
#    - 运动、体检、疫苗接种的拖延
#    - 即时成本 vs 未来收益
#
# 【干预策略】
#
# 1. 承诺设备（Commitment Devices）
#    - 提前限制未来选择
#    - 例：定期定额储蓄、健身房年卡
#
# 2. 默认选项（Default Options）
#    - 自动加入养老金计划
#    - 利用惰性促进长期利益
#
# 3. 提醒与反馈
#    - 使未来后果更加凸显
#    - 减少心理距离
#
# 【实验证据】
#
# Thaler (1981) 经典实验：
# - 今天得到15美元 vs 一个月后得到X美元，X=20才无差异
# - 今天得到15美元 vs 一年后得到X美元，X=50才无差异
# - 今天得到15美元 vs 十年后得到X美元，X=100才无差异
