# 虽然启发式在很多情况下能快速得出合理答案，但也会导致系统性偏误（Biases）。
#
# 【理论背景】
#
# Herbert Simon (1955) 提出"有限理性"（Bounded Rationality）概念：
# - 人类认知能力有限
# - 计算成本高昂
# - 时间和注意力稀缺
# - 因此采用"满意化"而非"最优化"策略
#
# Daniel Kahneman 和 Amos Tversky (1974) 系统研究了判断中的启发式和偏误，
# 提出了著名的"启发式与偏误"（Heuristics and Biases）研究范式。
#
# 【与传统经济学的区别】
#
# 传统经济学假设：
# - 贝叶斯更新：正确使用先验概率和似然信息
# - 一致的概率判断：满足概率公理
# - 信息整合：能够正确加权所有相关信息
#
# 行为经济学发现：
# - 人们使用简化的启发式规则
# - 系统性偏离贝叶斯法则
# - 特定信息被过度或不足重视
#
# 【三大经典启发式】（Tversky & Kahneman, 1974）
#
# 1. 代表性启发式（Representativeness Heuristic）
#    - 根据与原型的相似性判断概率
#    - "看起来像什么就认为是什么"
#    - 导致：基率忽视、小数法则、合取谬误、回归谬误
#
# 2. 可得性启发式（Availability Heuristic）
#    - 根据回忆的容易程度判断频率/概率
#    - 容易想起的事件被认为更常见
#    - 导致：高估显著事件、低估抽象风险
#
# 3. 锚定与调整（Anchoring and Adjustment）
#    - 从初始值开始，调整不充分
#    - 即使锚是任意的也会影响判断
#    - 导致：估计偏向锚点
#
# 【主要认知偏误】
#
# 1. 基率忽视（Base Rate Neglect）
#    - 过度依赖个案信息，忽视先验概率
#    - 典型案例：医疗诊断、嫌疑人识别
#
# 2. 过度自信（Overconfidence）
#    - 高估自己判断的准确性
#    - 置信区间过窄
#
# 3. 后见之明偏误（Hindsight Bias）
#    - "我早就知道会这样"
#    - 事后回顾时高估预见能力
#
# 4. 确认偏误（Confirmation Bias）
#    - 倾向于寻找支持已有观点的证据
#    - 忽视或低估反面证据
#
# 5. 合取谬误（Conjunction Fallacy）
#    - 认为 P(A且B) > P(A)
#    - Linda问题经典案例
#
# 【经济与金融影响】
#
# 1. 金融市场
#    - 过度交易（过度自信）
#    - 追涨杀跌（代表性）
#    - 恐慌与泡沫（可得性）
#
# 2. 保险决策
#    - 高估小概率事件（飞机失事）
#    - 低估常见风险（车祸）
#
# 3. 投资行为
#    - 本土偏好
#    - 处置效应
#    - 赌徒谬误
#
# 【重要启示】
#
# 1. 启发式在很多情况下是有效的
#    - 低成本、快速决策
#    - 在熟悉环境中表现良好
#
# 2. 了解偏误不一定能消除偏误
#    - 系统1的自动加工
#    - 需要刻意练习和环境设计
#
# 3. 可以通过制度设计减轻偏误影响
#    - 决策辅助工具
#    - 清单和流程
#    - 多元化决策机制
