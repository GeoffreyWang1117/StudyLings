# 说明：
# 前景理论（Prospect Theory）是由Daniel Kahneman和Amos Tversky于1979年提出的
# 描述性决策理论，2002年Kahneman因此获得诺贝尔经济学奖。
#
# 【理论背景】
# 传统期望效用理论（Expected Utility Theory, EUT）假设人们根据最终财富的效用
# 做决策，但大量实验证据表明人们的实际行为与EUT预测不符。
#
# 著名悖论：
# - Allais悖论（1953）：违反独立性公理
# - Ellsberg悖论（1961）：对模糊性的厌恶
#
# 【与期望效用理论的核心区别】
#
# 1. 参考点依赖（Reference Dependence）
#    - EUT：效用取决于最终财富水平 U(W)
#    - PT：价值取决于相对于参考点的变化 v(x - r)
#    - 参考点通常是现状（status quo），但可以是期望、目标等
#
# 2. 损失厌恶（Loss Aversion）
#    - 损失带来的负效用大于等量收益带来的正效用
#    - 实验发现：损失的心理影响约为收益的2-2.5倍
#    - "失去100元的痛苦 > 得到100元的快乐"
#
# 3. 敏感性递减（Diminishing Sensitivity）
#    - 价值函数在收益和损失两个方向都是凹的（边际递减）
#    - 收益区：凹函数 → 风险厌恶
#    - 损失区：凸函数 → 风险寻求
#
# 4. 概率加权（Probability Weighting）
#    - 人们不直接使用客观概率，而是使用决策权重
#    - 小概率被高估，大概率被低估
#    - 导致确定性效应和可能性效应
#
# 【价值函数】
# 价值函数的数学形式（Tversky & Kahneman, 1992）：
#
# v(x) = x^α              if x >= 0 （收益区）
# v(x) = -λ(-x)^β         if x < 0  （损失区）
#
# 典型参数估计：
# - α = β = 0.88（敏感性参数，< 1表示边际递减）
# - λ = 2.25（损失厌恶系数，> 1表示损失厌恶）
#
# 价值函数特征：
# - 过原点：v(0) = 0
# - 收益区递增凹：v'(x) > 0, v''(x) < 0 for x > 0
# - 损失区递增凸：v'(x) > 0, v''(x) > 0 for x < 0
# - 损失区比收益区更陡峭：|v(-x)| > |v(x)| for x > 0
#
# 【概率加权函数】
# Tversky-Kahneman形式（1992）：
# w(p) = p^γ / (p^γ + (1-p)^γ)^(1/γ)
#
# Prelec形式（1998）：
# w(p) = exp(-(-ln(p))^γ)
#
# 特征：
# - w(0) = 0, w(1) = 1
# - 在p较小时 w(p) > p（高估小概率）
# - 在p较大时 w(p) < p（低估大概率）
# - 存在交叉点约在p = 0.3-0.4
# - γ越小，S形越明显
#
# 【重要行为现象】
#
# 1. 确定性效应（Certainty Effect）
#    - 人们对确定结果给予过高权重
#    - 例：80%赢4000 vs 确定得到3000，多数选后者
#
# 2. 反射效应（Reflection Effect）
#    - 收益区的风险厌恶 ↔ 损失区的风险寻求
#    - 同一个人在不同框架下表现相反的风险态度
#
# 3. 框架效应（Framing Effect）
#    - 同一问题的不同表述导致不同选择
#    - 经典案例："亚洲疾病问题"
#
# 4. 禀赋效应（Endowment Effect）
#    - 拥有物品后对其估值上升
#    - 卖价（WTA）> 买价（WTP）
#    - 源于损失厌恶：放弃拥有物 = 损失
#
# 【实验证据】
# Kahneman & Tversky (1979) 的经典实验：
# 问题1：选择A（确定得2400）还是B（25%得10000，75%得0）？
#        多数选A（风险厌恶）
# 问题2：选择C（确定亏2400）还是D（25%亏10000，75%亏0）？
#        多数选D（风险寻求）
#
# 【应用领域】
# - 金融市场：处置效应（过早卖出盈利股，过久持有亏损股）
# - 保险决策：对小概率大损失的过度保险
# - 消费行为：价格促销的框架效应
# - 谈判：参考点对谈判结果的影响
# - 政策设计：利用框架效应引导行为
