// 练习 1: 异步编程简介
//
// 在这个练习中，我们将了解什么是异步编程，以及它与同步编程的区别。
//
// JavaScript 是单线程的，但通过异步编程，我们可以在等待某些操作完成时
// 继续执行其他代码，而不是阻塞整个程序。

console.log('1. 这是第一行');

// setTimeout 是一个异步函数，它会在指定的时间后执行回调函数
setTimeout(() => {
  console.log('2. 这是异步执行的代码（1秒后）');
}, 1000);

console.log('3. 这是第三行');

// 问题：请观察输出顺序，思考为什么是这样的顺序？
//
// 预期输出顺序：
// 1. 这是第一行
// 3. 这是第三行
// 2. 这是异步执行的代码（1秒后）
//
// 这展示了异步编程的核心概念：不等待耗时操作完成，而是继续执行后续代码

